class RoomToFPDataset(Dataset):
    """
    Dataset for prepared RoomToFP .npz samples.

    Supports split files generated by prepare_roomtofp_dataset.py: train.txt, val.txt, test.txt

    The training split can apply polygon-safe geometric augmentation. When an
    image is flipped/rotated, the wall/opening/furniture masks and normalised
    polygon corner coordinates are transformed in the same way.
    """

    def __init__(self, root: str, split: str | None = None, augment: bool = False):
        self.root = Path(root)
        self.split = split
        self.augment = augment
        self.samples_dir = self.root / "samples" if (self.root / "samples").exists() else self.root

        if split and split != "all":
            split_file = self.root / f"{split}.txt"
            if not split_file.exists():
                raise FileNotFoundError(
                    f"Split file not found: {split_file}. "
                    "Run prepare_roomtofp_dataset.py first, or use split='all'."
                )

            names = [line.strip() for line in split_file.read_text(encoding="utf-8").splitlines() if line.strip()]
            self.files = []
            missing = []
            for name in names:
                p = Path(name)
                if not p.is_absolute():
                    p = self.samples_dir / p.name
                if p.exists():
                    self.files.append(p)
                else:
                    missing.append(str(p))
            if missing:
                print(f"--Warning-- {len(missing)} sample(s) listed in {split_file.name} were missing. First missing: {missing[0]}")
        else:
            self.files = sorted(self.samples_dir.glob("*.npz"))

        if not self.files:
            raise FileNotFoundError(f"No .npz samples found in {self.samples_dir} for split={split!r}")

    def __len__(self):
        return len(self.files)

    def _augment_sample(
        self,
        obs_hwc: np.ndarray,
        furniture_mask: np.ndarray,
        wall_mask: np.ndarray,
        opening_mask: np.ndarray,
        polygon_xy: np.ndarray,
        room_mask: np.ndarray,
        boundary_mask: np.ndarray,
        corner_heatmap: np.ndarray,
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        """
        Apply square-image safe flips/rotations to tensors and polygons
        """
        if not self.augment:
            return obs_hwc, furniture_mask, wall_mask, opening_mask, polygon_xy, room_mask, boundary_mask, corner_heatmap

        # Copy so we never mutate np.load views
        obs_hwc = obs_hwc.copy()
        furniture_mask = furniture_mask.copy()
        wall_mask = wall_mask.copy()
        opening_mask = opening_mask.copy()
        polygon_xy = polygon_xy.copy()
        room_mask = room_mask.copy()
        boundary_mask = boundary_mask.copy()
        corner_heatmap = corner_heatmap.copy()

        # Horizontal flip with 50% prob: x -> 1 - x
        if random.random() < 0.5:
            obs_hwc = np.flip(obs_hwc, axis=1).copy()
            furniture_mask = np.flip(furniture_mask, axis=2).copy()
            wall_mask = np.flip(wall_mask, axis=2).copy()
            opening_mask = np.flip(opening_mask, axis=2).copy()
            room_mask = np.flip(room_mask, axis=2).copy()
            boundary_mask = np.flip(boundary_mask, axis=2).copy()
            corner_heatmap = np.flip(corner_heatmap, axis=2).copy()
            polygon_xy[..., 0] = 1.0 - polygon_xy[..., 0]  # polygon coords norm

        # Vertical flip with 50% prob: y -> 1 - y
        if random.random() < 0.5:
            obs_hwc = np.flip(obs_hwc, axis=0).copy()
            furniture_mask = np.flip(furniture_mask, axis=1).copy()
            wall_mask = np.flip(wall_mask, axis=1).copy()
            opening_mask = np.flip(opening_mask, axis=1).copy()
            room_mask = np.flip(room_mask, axis=1).copy()
            boundary_mask = np.flip(boundary_mask, axis=1).copy()
            corner_heatmap = np.flip(corner_heatmap, axis=1).copy()
            polygon_xy[..., 1] = 1.0 - polygon_xy[..., 1]

        # 90-degree rotations. For np.rot90(k=1), pixel mapping is
        # old (x,y) -> new (x'=y, y'=1-x) in normalised image coordinates
        k = random.randint(0, 3)  # randomly chooses 0, 90, 180, 270 degree rotation
        if k:
            obs_hwc = np.rot90(obs_hwc, k=k, axes=(0, 1)).copy()
            furniture_mask = np.rot90(furniture_mask, k=k, axes=(1, 2)).copy()
            wall_mask = np.rot90(wall_mask, k=k, axes=(1, 2)).copy()
            opening_mask = np.rot90(opening_mask, k=k, axes=(1, 2)).copy()
            room_mask = np.rot90(room_mask, k=k, axes=(1, 2)).copy()
            boundary_mask = np.rot90(boundary_mask, k=k, axes=(1, 2)).copy()
            corner_heatmap = np.rot90(corner_heatmap, k=k, axes=(1, 2)).copy()
            x = polygon_xy[..., 0].copy()
            y = polygon_xy[..., 1].copy()
            if k == 1:
                polygon_xy[..., 0] = y  # x' = y
                polygon_xy[..., 1] = 1.0 - x  # y' = 1 - x
            elif k == 2:
                polygon_xy[..., 0] = 1.0 - x  # x' = 1 - x
                polygon_xy[..., 1] = 1.0 - y  # y' = 1 - y
            elif k == 3:
                polygon_xy[..., 0] = 1.0 - y  # x' = 1 - y
                polygon_xy[..., 1] = x  # y' = x

        polygon_xy = np.clip(polygon_xy, 0.0, 1.0)
        return obs_hwc, furniture_mask, wall_mask, opening_mask, polygon_xy, room_mask, boundary_mask, corner_heatmap

    @staticmethod
    def _rasterize_room_masks_from_polygons(polygon_xy: np.ndarray, corner_valid: np.ndarray, room_valid: np.ndarray, h: int, w: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """
        Improvement v3: fallback target builder for older .npz datasets that do not yet contain room_mask, boundary_mask, or corner_heatmap.
        """
        max_rooms = int(polygon_xy.shape[0])
        room_mask = np.zeros((max_rooms, h, w), dtype=np.float32)
        boundary_mask = np.zeros((1, h, w), dtype=np.float32)
        corner_heatmap = np.zeros((1, h, w), dtype=np.float32)
        for ri in range(max_rooms):
            if room_valid[ri] <= 0.5:
                continue
            n = int(corner_valid[ri].sum())
            if n < 3:
                continue
            pts = polygon_xy[ri, :n].copy()
            pts[:, 0] = np.clip(np.round(pts[:, 0] * (w - 1)), 0, w - 1)
            pts[:, 1] = np.clip(np.round(pts[:, 1] * (h - 1)), 0, h - 1)
            pts = pts.astype(np.int32)
            cv2.fillPoly(room_mask[ri], [pts], 1.0)
            cv2.polylines(boundary_mask[0], [pts], True, 1.0, thickness=3, lineType=cv2.LINE_AA)
            for x, y in pts:
                cv2.circle(corner_heatmap[0], (int(x), int(y)), 4, 1.0, thickness=-1)
        boundary_mask = np.clip(boundary_mask, 0.0, 1.0).astype(np.float32)
        corner_heatmap = np.clip(cv2.GaussianBlur(corner_heatmap[0], (0, 0), 1.0), 0.0, 1.0)[None, ...].astype(np.float32)
        return room_mask, boundary_mask, corner_heatmap

    def __getitem__(self, idx):
        d = np.load(self.files[idx])

        obs_hwc = d["observation"].astype(np.float32)
        h, w = obs_hwc.shape[:2]
        furniture_mask = d["furniture_mask"].astype(np.float32) if "furniture_mask" in d else np.zeros((1, h, w), np.float32)
        wall_mask = d["wall_mask"].astype(np.float32) if "wall_mask" in d else np.zeros((1, h, w), np.float32)
        opening_mask = d["opening_mask"].astype(np.float32) if "opening_mask" in d else np.zeros((1, h, w), np.float32)
        # Keep mask targets strictly binary/0-1. Some rendered opening masks can contain value 2 where line strokes overlap,
        # and BCE/Dice losses expect targets in the 0-1 range.
        furniture_mask = np.clip(furniture_mask, 0.0, 1.0).astype(np.float32)
        wall_mask = np.clip(wall_mask, 0.0, 1.0).astype(np.float32)
        opening_mask = np.clip(opening_mask, 0.0, 1.0).astype(np.float32)

        polygon_xy = d["polygon_xy"].astype(np.float32)
        corner_valid_np = d["corner_valid"].astype(np.float32)
        room_valid_np = d["room_valid"].astype(np.float32)

        if "room_mask" in d:
            room_mask = np.clip(d["room_mask"].astype(np.float32), 0.0, 1.0)
            boundary_mask = np.clip(d["boundary_mask"].astype(np.float32), 0.0, 1.0) if "boundary_mask" in d else np.maximum(wall_mask, opening_mask)
            corner_heatmap = np.clip(d["corner_heatmap"].astype(np.float32), 0.0, 1.0) if "corner_heatmap" in d else np.zeros((1, h, w), np.float32)
        else:
            room_mask, boundary_mask, corner_heatmap = self._rasterize_room_masks_from_polygons(polygon_xy, corner_valid_np, room_valid_np, h, w)

        obs_hwc, furniture_mask, wall_mask, opening_mask, polygon_xy, room_mask, boundary_mask, corner_heatmap = self._augment_sample(
            obs_hwc, furniture_mask, wall_mask, opening_mask, polygon_xy, room_mask, boundary_mask, corner_heatmap
        )

        obs_chw = obs_hwc.transpose(2, 0, 1).astype(np.float32)  # conv HWC to CHW as expected by PyTorch

        return {
            "x": torch.from_numpy(obs_chw),
            "polygon_xy": torch.from_numpy(polygon_xy),
            "corner_valid": torch.from_numpy(corner_valid_np),
            "room_valid": torch.from_numpy(room_valid_np),
            "room_class": torch.from_numpy(d["room_class"].astype(np.int64)),
            "furniture_mask": torch.from_numpy(furniture_mask),
            "wall_mask": torch.from_numpy(wall_mask),
            "opening_mask": torch.from_numpy(opening_mask),
            # Improvement v3: room instance masks and structural heatmaps supervise query masks and sharper boundaries/corners.
            "room_mask": torch.from_numpy(room_mask),
            "boundary_mask": torch.from_numpy(boundary_mask),
            "corner_heatmap": torch.from_numpy(corner_heatmap),
        }

    @property
    def in_channels(self) -> int:
        """
        Loads first sample and returns num of input channels
        """
        d = np.load(self.files[0])
        return int(d["observation"].shape[-1])

    @property
    def max_rooms(self) -> int:
        """
        Returns num of room slots in dataset
        """
        d = np.load(self.files[0])
        return int(d["polygon_xy"].shape[0])

    @property
    def max_corners(self) -> int:
        """
        Returns num of corner slots per room
        """
        d = np.load(self.files[0])
        return int(d["polygon_xy"].shape[1])


@dataclass
class LossConfig:
    """
    Stores important loss function settings
    Model predicts multiple things with its own loss that this class controls
    total loss =
    room validity loss + corner validity loss + room class loss + coord_weight * polygon coordinate loss + aux_wall * wall mask loss
      + aux_opening * opening mask loss + aux_furniture * furniture mask loss, if enabled
    """
    use_furniture: bool = False
    aux_furniture: float = 0.0  # loss weight for furn mask pred
    aux_wall: float = 0.8  # controls how much wall mask loss affects total loss
    aux_opening: float = 0.7  # controls how much opening mask loss affects total loss
    aux_boundary: float = 0.35  # Improvement v3: explicit boundary heatmap loss sharpens structural outlines.
    aux_corner_heatmap: float = 0.25  # Improvement v3: dense corner heatmap supervision helps the polygon branch learn corner locations.
    aux_room_mask: float = 1.0  # Improvement v3: per-room query masks make room objects learn full spatial extents, not only corner coordinates.
    coord_weight: float = 5.0  # controls how strongly polygon coordinate errors are penalized; compares predicted room corner to target
    polygon_edge_weight: float = 0.75  # Improvement v3: side-length loss discourages collapsed/skewed polygons.
    polygon_angle_weight: float = 0.20  # Improvement v4: encourages clean Manhattan-like turns and discourages jagged polygon sequences.
    polygon_area_weight: float = 0.35  # Improvement v4: matches room area so polygons do not collapse even when individual corners are close.
    room_overlap_weight: float = 0.10  # Improvement v4: discourages multiple room query masks from covering the same room area.
    # Improvement v5: directly supervise the predicted polygon shape by softly rasterising corner_xy and comparing it to the GT room mask, RoomFormer-style.
    polygon_raster_weight: float = 1.0
    polygon_raster_size: int = 64
    # Improvement v5: apply a smaller version of polygon losses to intermediate decoder outputs.
    aux_decoder_weight: float = 0.35
    boundary_weight: float = 0.15  # Improvement v3: edge loss inside mask loss encourages sharper wall/opening boundaries.
    room_pos_weight_max: float = 8.0  # Improvement v3: positive weighting prevents empty room slots/background from dominating.
    dice_weight: float = 1.0  # controls how much dice loss contributes when using bce_dice or focal_dice; focuses on overlap between preds and true foreground
    focal_gamma: float = 2.0  # used if maskLoss = focalDice; focalLoss reduces impo of easy examples and focuses more on misclassified pixels
    mask_loss: str = "focal_dice"  # bce: compares each pixel independently; simple, but can struggle with sparse masks,
                                 # bce_dice: balances pixel-level correctness and foreground overlap, usually better for opening/wall masks,
                                 # focal_dice: focalLoss + diceLoss - useful when masks are imbalanced
    hungarian: bool = True  # enables Hungarian matching for room preds; model predicts a fixed set of room slots, but real rooms do not have a natural order;
                            # bedroom could be predicted in slot 3 while the target bedroom is stored in slot 1; without matching, model would be punished even
                            # if it predicted the correct room in a different slot. Hungarian matching solves this by finding the best assignment between predicted rooms & ground-truth rooms
                            # So the loss compares each prediction to the most suitable target room.
    cyclic: bool = True  # enables cyclic/reversed polygon alignment
    match_class_weight: float = 0.25  # controls how much room class similarity matters during Hungarian matching
    match_room_conf_weight: float = 0.15  # controls how much predicted room confidence matters during matching


def _cfg_from_args(args: Any | None) -> LossConfig:
    if args is None:
        return LossConfig()
    return LossConfig(
        use_furniture=bool(getattr(args, "use_furniture_loss", False)),
        aux_furniture=float(getattr(args, "aux_furniture", 0.0)),
        aux_wall=float(getattr(args, "aux_wall", 0.8)),
        aux_opening=float(getattr(args, "aux_opening", 0.7)),
        aux_boundary=float(getattr(args, "aux_boundary", 0.35)),
        aux_corner_heatmap=float(getattr(args, "aux_corner_heatmap", 0.25)),
        aux_room_mask=float(getattr(args, "aux_room_mask", 1.0)),
        coord_weight=float(getattr(args, "coord_weight", 5.0)),
        polygon_edge_weight=float(getattr(args, "polygon_edge_weight", 0.75)),
        polygon_angle_weight=float(getattr(args, "polygon_angle_weight", 0.20)),
        polygon_area_weight=float(getattr(args, "polygon_area_weight", 0.35)),
        room_overlap_weight=float(getattr(args, "room_overlap_weight", 0.10)),
        polygon_raster_weight=float(getattr(args, "polygon_raster_weight", 1.0)),
        polygon_raster_size=int(getattr(args, "polygon_raster_size", 64)),
        aux_decoder_weight=float(getattr(args, "aux_decoder_weight", 0.35)),
        boundary_weight=float(getattr(args, "boundary_weight", 0.15)),
        room_pos_weight_max=float(getattr(args, "room_pos_weight_max", 8.0)),
        dice_weight=float(getattr(args, "dice_weight", 1.0)),
        focal_gamma=float(getattr(args, "focal_gamma", 2.0)),
        mask_loss=str(getattr(args, "mask_loss", "bce_dice")),
        hungarian=not bool(getattr(args, "no_hungarian", False)),
        cyclic=not bool(getattr(args, "no_cyclic", False)),
        match_class_weight=float(getattr(args, "match_class_weight", 0.25)),
        match_room_conf_weight=float(getattr(args, "match_room_conf_weight", 0.15)),
    )


def _balanced_bce_with_logits(logits: torch.Tensor, target: torch.Tensor, max_pos_weight: float = 20.0) -> torch.Tensor:
    """
    Improvement v3: Binary cross entropy with dynamic positive weighting so sparse foreground targets do not get overwhelmed by background.
    """
    target = target.float().clamp(0.0, 1.0)
    pos = target.sum().detach()
    neg = torch.numel(target) - pos
    if float(pos.item()) <= 0.0:
        return F.binary_cross_entropy_with_logits(logits, target)
    pos_weight = (neg / pos.clamp_min(1.0)).clamp(1.0, float(max_pos_weight)).to(device=logits.device, dtype=logits.dtype)
    return F.binary_cross_entropy_with_logits(logits, target, pos_weight=pos_weight)


def _edge_l1_loss_from_logits(logits: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
    """
    Improvement v3: lightweight boundary loss for masks so predicted walls/openings become less blurry and less blob-like.
    """
    prob = torch.sigmoid(logits)
    target = target.float().clamp(0.0, 1.0)
    pred_dilate = F.max_pool2d(prob, kernel_size=3, stride=1, padding=1)
    pred_erode = -F.max_pool2d(-prob, kernel_size=3, stride=1, padding=1)
    tgt_dilate = F.max_pool2d(target, kernel_size=3, stride=1, padding=1)
    tgt_erode = -F.max_pool2d(-target, kernel_size=3, stride=1, padding=1)
    pred_edge = (pred_dilate - pred_erode).clamp(0.0, 1.0)
    tgt_edge = (tgt_dilate - tgt_erode).clamp(0.0, 1.0)
    return F.l1_loss(pred_edge, tgt_edge)


def _polygon_edge_l1(pred_xy: torch.Tensor, target_xy: torch.Tensor, room_valid: torch.Tensor, corner_valid: torch.Tensor) -> torch.Tensor:
    """
    Improvement v3: compare polygon side lengths so predicted rooms keep better proportions instead of only matching individual points.
    """
    losses = []
    bsz, max_rooms, _, _ = pred_xy.shape
    for bi in range(bsz):
        for ri in range(max_rooms):
            if room_valid[bi, ri] <= 0.5:
                continue
            n = int(corner_valid[bi, ri].sum().item())
            if n < 3:
                continue
            p = pred_xy[bi, ri, :n]
            t = target_xy[bi, ri, :n]
            p_len = torch.linalg.norm(torch.roll(p, shifts=-1, dims=0) - p, dim=-1)
            t_len = torch.linalg.norm(torch.roll(t, shifts=-1, dims=0) - t, dim=-1)
            losses.append(torch.mean(torch.abs(p_len - t_len)))
    if not losses:
        return torch.zeros((), device=pred_xy.device, dtype=pred_xy.dtype)
    return torch.stack(losses).mean()


def _polygon_signed_area(poly: torch.Tensor) -> torch.Tensor:
    x = poly[:, 0]
    y = poly[:, 1]
    return 0.5 * torch.sum(x * torch.roll(y, shifts=-1, dims=0) - y * torch.roll(x, shifts=-1, dims=0))


def _polygon_area_l1(pred_xy: torch.Tensor, target_xy: torch.Tensor, room_valid: torch.Tensor, corner_valid: torch.Tensor) -> torch.Tensor:
    """
    Improvement v4: compare polygon areas so the model is penalised when a room collapses into a thin line or tiny blob.
    """
    losses = []
    bsz, max_rooms, _, _ = pred_xy.shape
    for bi in range(bsz):
        for ri in range(max_rooms):
            if room_valid[bi, ri] <= 0.5:
                continue
            n = int(corner_valid[bi, ri].sum().item())
            if n < 3:
                continue
            p_area = torch.abs(_polygon_signed_area(pred_xy[bi, ri, :n]))
            t_area = torch.abs(_polygon_signed_area(target_xy[bi, ri, :n]))
            losses.append(torch.abs(p_area - t_area))
    if not losses:
        return torch.zeros((), device=pred_xy.device, dtype=pred_xy.dtype)
    return torch.stack(losses).mean()


def _polygon_angle_loss(pred_xy: torch.Tensor, room_valid: torch.Tensor, corner_valid: torch.Tensor) -> torch.Tensor:
    """
    Improvement v4: softly regularise edges toward horizontal/vertical Manhattan structure.
    It only uses predicted polygons, so it complements coordinate matching without depending on target edge ordering quality.
    """
    losses = []
    bsz, max_rooms, _, _ = pred_xy.shape
    for bi in range(bsz):
        for ri in range(max_rooms):
            if room_valid[bi, ri] <= 0.5:
                continue
            n = int(corner_valid[bi, ri].sum().item())
            if n < 3:
                continue
            p = pred_xy[bi, ri, :n]
            edges = torch.roll(p, shifts=-1, dims=0) - p
            edge_len = torch.linalg.norm(edges, dim=-1).clamp_min(1e-6)
            unit = torch.abs(edges / edge_len.unsqueeze(-1))
            # For Manhattan edges, one component should be near 1 and the other near 0.
            losses.append(torch.mean(torch.minimum(unit[:, 0], unit[:, 1])))
    if not losses:
        return torch.zeros((), device=pred_xy.device, dtype=pred_xy.dtype)
    return torch.stack(losses).mean()


def _room_mask_overlap_loss(logits: torch.Tensor, room_valid: torch.Tensor) -> torch.Tensor:
    """
    Improvement v4: reduce duplicate/overlapping room query masks by penalising foreground overlap between valid room slots.
    """
    prob = torch.sigmoid(logits) * room_valid.unsqueeze(-1).unsqueeze(-1)
    losses = []
    for bi in range(prob.shape[0]):
        ids = torch.nonzero(room_valid[bi] > 0.5, as_tuple=False).flatten()
        if ids.numel() <= 1:
            continue
        masks = prob[bi, ids].flatten(1)
        inter = masks @ masks.t()
        area = masks.sum(dim=1).clamp_min(1e-6)
        union = (area[:, None] + area[None, :] - inter).clamp_min(1e-6)
        iou = inter / union
        eye = torch.eye(iou.shape[0], device=iou.device, dtype=torch.bool)
        losses.append(iou.masked_fill(eye, 0.0).sum() / max(1, iou.numel() - iou.shape[0]))
    if not losses:
        return torch.zeros((), device=logits.device, dtype=logits.dtype)
    return torch.stack(losses).mean()


def _room_query_mask_loss(logits: torch.Tensor, target: torch.Tensor, room_valid: torch.Tensor, cfg: LossConfig) -> torch.Tensor:
    """
    Improvement v3: supervise one mask per room query, MaskFormer-style, after Hungarian target reordering.
    """
    target = target.float().clamp(0.0, 1.0)
    per_room = []
    for bi in range(logits.shape[0]):
        valid_ids = torch.nonzero(room_valid[bi] > 0.5, as_tuple=False).flatten()
        for ri in valid_ids.tolist():
            per_room.append(_mask_loss(logits[bi:bi+1, ri:ri+1], target[bi:bi+1, ri:ri+1], cfg))
    if not per_room:
        return torch.zeros((), device=logits.device, dtype=logits.dtype)
    return torch.stack(per_room).mean()



def _soft_triangle_mask(tri: torch.Tensor, grid_xy: torch.Tensor, sharpness: float = 140.0) -> torch.Tensor:
    """
    Improvement v5: differentiable soft rasterisation primitive.

    tri: [3,2] normalised xy vertices. grid_xy: [S,S,2] normalised xy sample grid.
    Returns a soft inside mask for the triangle. This is a lightweight substitute for
    RoomFormer's differentiable polygon rasterisation and keeps gradients flowing into corner_xy.
    """
    a, b, c = tri[0], tri[1], tri[2]
    area = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
    orient = torch.where(area >= 0, torch.ones_like(area), -torch.ones_like(area))

    def edge(p0: torch.Tensor, p1: torch.Tensor) -> torch.Tensor:
        return orient * ((p1[0] - p0[0]) * (grid_xy[..., 1] - p0[1]) - (p1[1] - p0[1]) * (grid_xy[..., 0] - p0[0]))

    e0 = torch.sigmoid(sharpness * edge(a, b))
    e1 = torch.sigmoid(sharpness * edge(b, c))
    e2 = torch.sigmoid(sharpness * edge(c, a))
    return e0 * e1 * e2


def _soft_polygon_mask(poly: torch.Tensor, grid_xy: torch.Tensor) -> torch.Tensor:
    """
    Improvement v5: differentiably rasterise an ordered polygon into a soft mask.

    The polygon is decomposed into a triangle fan around its centroid and the soft
    triangle masks are unioned. This handles most RoomToFP room polygons well enough
    for training pressure and is fully differentiable w.r.t. corner_xy.
    """
    n = int(poly.shape[0])
    if n < 3:
        return torch.zeros(grid_xy.shape[:2], device=poly.device, dtype=poly.dtype)
    center = poly.mean(dim=0)
    union = torch.zeros(grid_xy.shape[:2], device=poly.device, dtype=poly.dtype)
    for i in range(n):
        tri = torch.stack([center, poly[i], poly[(i + 1) % n]], dim=0)
        tri_mask = _soft_triangle_mask(tri, grid_xy)
        union = 1.0 - (1.0 - union) * (1.0 - tri_mask)
    return union.clamp(0.0, 1.0)


def _polygon_raster_loss(
    pred_xy: torch.Tensor,
    target_room_mask: torch.Tensor,
    room_valid: torch.Tensor,
    corner_valid: torch.Tensor,
    raster_size: int = 64,
) -> torch.Tensor:
    """
    Improvement v5: RoomFormer-style polygon rasterisation loss.

    This loss supervises the predicted corner polygon itself. It prevents the model
    from learning a decent room_mask_logits branch while leaving corner_xy inaccurate.
    The target room masks are downsampled to keep training affordable.
    """
    if target_room_mask.ndim != 4:
        return torch.zeros((), device=pred_xy.device, dtype=pred_xy.dtype)

    s = int(max(16, raster_size))
    target_small = F.interpolate(target_room_mask.float(), size=(s, s), mode="area").clamp(0.0, 1.0)
    yy, xx = torch.meshgrid(
        torch.linspace(0.0, 1.0, s, device=pred_xy.device, dtype=pred_xy.dtype),
        torch.linspace(0.0, 1.0, s, device=pred_xy.device, dtype=pred_xy.dtype),
        indexing="ij",
    )
    grid_xy = torch.stack([xx, yy], dim=-1)

    losses = []
    bsz, max_rooms, _, _ = pred_xy.shape
    for bi in range(bsz):
        for ri in range(max_rooms):
            if room_valid[bi, ri] <= 0.5:
                continue
            n = int(corner_valid[bi, ri].sum().item())
            if n < 3:
                continue
            pred_mask = _soft_polygon_mask(pred_xy[bi, ri, :n], grid_xy)
            tgt = target_small[bi, ri]
            inter = (pred_mask * tgt).sum()
            denom = pred_mask.sum() + tgt.sum()
            dice_loss = 1.0 - ((2.0 * inter + 1e-6) / (denom + 1e-6))
            bce = F.binary_cross_entropy(pred_mask.clamp(1e-4, 1.0 - 1e-4), tgt)
            losses.append(dice_loss + 0.25 * bce)

    if not losses:
        return torch.zeros((), device=pred_xy.device, dtype=pred_xy.dtype)
    return torch.stack(losses).mean()


def _polygon_supervision_terms(pred: dict[str, torch.Tensor], batch: dict[str, torch.Tensor], cfg: LossConfig) -> tuple[torch.Tensor, dict[str, torch.Tensor]]:
    """
    Shared polygon-only supervision used by the final output and auxiliary decoder outputs.
    """
    room_valid = batch["room_valid"]
    corner_valid = batch["corner_valid"]
    valid_logits = pred["room_valid_logits"]
    corner_logits = pred["corner_valid_logits"]
    xy = pred["corner_xy"]
    target_xy = batch["polygon_xy"]

    room_bce = _balanced_bce_with_logits(valid_logits, room_valid, max_pos_weight=cfg.room_pos_weight_max)
    corner_raw = F.binary_cross_entropy_with_logits(corner_logits, corner_valid, reduction="none")
    corner_room_mask = room_valid.unsqueeze(-1)
    corner_bce = (corner_raw * corner_room_mask).sum() / (corner_room_mask.sum() * corner_valid.shape[-1]).clamp_min(1.0)

    mask = (room_valid.unsqueeze(-1) * corner_valid).unsqueeze(-1)
    coord_l1 = (torch.abs(xy - target_xy) * mask).sum() / mask.sum().clamp_min(1.0)
    edge_l1 = _polygon_edge_l1(xy, target_xy, room_valid, corner_valid)
    area_l1 = _polygon_area_l1(xy, target_xy, room_valid, corner_valid)
    angle_loss = _polygon_angle_loss(xy, room_valid, corner_valid)

    class_loss = F.cross_entropy(
        pred["room_class_logits"].flatten(0, 1),
        batch["room_class"].flatten(),
        reduction="none",
    )
    class_loss = (class_loss.view_as(room_valid) * room_valid).sum() / room_valid.sum().clamp_min(1.0)

    polygon_raster = torch.zeros((), device=xy.device, dtype=xy.dtype)
    if cfg.polygon_raster_weight > 0 and "room_mask" in batch:
        polygon_raster = _polygon_raster_loss(
            xy,
            batch["room_mask"],
            room_valid,
            corner_valid,
            raster_size=cfg.polygon_raster_size,
        )

    total = (
        room_bce
        + corner_bce
        + (cfg.coord_weight * coord_l1)
        + (cfg.polygon_edge_weight * edge_l1)
        + (cfg.polygon_area_weight * area_l1)
        + (cfg.polygon_angle_weight * angle_loss)
        + class_loss
        + (cfg.polygon_raster_weight * polygon_raster)
    )
    parts = {
        "room_bce": room_bce,
        "corner_bce": corner_bce,
        "coord_l1": coord_l1,
        "edge_l1": edge_l1,
        "area_l1": area_l1,
        "angle": angle_loss,
        "class": class_loss,
        "polygon_raster_loss": polygon_raster,
    }
    return total, parts


def _dice_from_logits(logits: torch.Tensor, target: torch.Tensor, threshold: float = 0.5) -> torch.Tensor:
    """
    calculates dice score b/w predicted mask and ground truth
    Dice = 2 * overlap / (prediction area + target area)
    """
    pred = (torch.sigmoid(logits) >= threshold).float()
    return (2 * (pred * target).sum() + 1e-6) / (pred.sum() + target.sum() + 1e-6)


def _dice_loss_from_logits(logits: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
    """
    Calculates dice loss
    Wall and opening masks are sparse. Most pixels are background Plain BCE can be dominated by background pixels.
    Dice loss focuses on foreground overlap, which is important for:
    - walls
    - openings
    - furniture masks
    """
    prob = torch.sigmoid(logits)  # conv to probs
    dims = tuple(range(1, prob.ndim))
    inter = (prob * target).sum(dim=dims)  # calc soft overlap
    denom = prob.sum(dim=dims) + target.sum(dim=dims)  # pred + target foreground amt
    return (1.0 - ((2.0 * inter + 1e-6) / (denom + 1e-6))).mean()


def _focal_loss_from_logits(logits: torch.Tensor, target: torch.Tensor, gamma: float = 2.0) -> torch.Tensor:
    bce = F.binary_cross_entropy_with_logits(logits, target, reduction="none")
    pt = torch.exp(-bce)
    return (((1.0 - pt) ** gamma) * bce).mean()


def _mask_loss(logits: torch.Tensor, target: torch.Tensor, cfg: LossConfig) -> torch.Tensor:
    target = target.float().clamp(0.0, 1.0)
    if cfg.mask_loss == "bce":
        loss = _balanced_bce_with_logits(logits, target)
    elif cfg.mask_loss == "focal_dice":
        loss = _focal_loss_from_logits(logits, target, cfg.focal_gamma) + cfg.dice_weight * _dice_loss_from_logits(logits, target)
    else:
        # default: BCE + Dice. This is much stronger than plain BCE for sparse wall/opening masks.
        loss = _balanced_bce_with_logits(logits, target) + cfg.dice_weight * _dice_loss_from_logits(logits, target)
    if cfg.boundary_weight > 0:
        loss = loss + cfg.boundary_weight * _edge_l1_loss_from_logits(logits, target)
    return loss


def _best_cyclic_target(pred_xy: torch.Tensor, target_xy: torch.Tensor, n: int, cyclic: bool) -> tuple[torch.Tensor, float]:
    """
    Return target corners aligned to predicted order and the alignment cost.

    pred_xy: [C,2], target_xy: [C,2], n valid target corners.
    We compare cyclic shifts and reversed cyclic shifts so the loss does not punish
    identical polygons simply because the annotation starts from a different corner.
    """
    c = pred_xy.shape[0]
    if n <= 0:
        return target_xy.clone(), 0.0

    pred_part = pred_xy[:n].detach()
    tgt = target_xy[:n].detach()

    candidates = [tgt]
    if cyclic and n > 1:
        for shift in range(1, n):
            candidates.append(torch.roll(tgt, shifts=-shift, dims=0))
        rev = torch.flip(tgt, dims=[0])
        for shift in range(0, n):
            candidates.append(torch.roll(rev, shifts=-shift, dims=0))

    best = candidates[0]
    best_cost = torch.mean(torch.abs(pred_part - best)).item()
    for cand in candidates[1:]:
        cost = torch.mean(torch.abs(pred_part - cand)).item()
        if cost < best_cost:
            best_cost = cost
            best = cand

    aligned = torch.zeros_like(target_xy)
    aligned[:n] = best
    if n < c:
        aligned[n:] = 0.0
    return aligned, float(best_cost)


def _greedy_assignment(cost: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    rows = []  # predicted room slots
    cols = []  # ground truth rooms; cost = how bad the pred-target match is
    used_r = set()
    used_c = set()
    flat = [(float(cost[r, c]), r, c) for r in range(cost.shape[0]) for c in range(cost.shape[1])]
    for _, r, c in sorted(flat, key=lambda x: x[0]):
        if r not in used_r and c not in used_c:
            used_r.add(r)
            used_c.add(c)
            rows.append(r)
            cols.append(c)

    return np.array(rows, dtype=np.int64), np.array(cols, dtype=np.int64)


def _match_and_reorder_targets(pred: dict[str, torch.Tensor], batch: dict[str, torch.Tensor], cfg: LossConfig) -> dict[str, torch.Tensor]:
    """
    Hungarian-match unordered predicted rooms to GT rooms.

    The original fixed-slot loss assumes room 0 must match room 0, etc. That is
    fragile because rooms are unordered objects. This function builds matched
    target tensors where each predicted slot is assigned its best GT room.

    A floorplan’s rooms are objects, not ordered sequence entries.
    If the model predicts the kitchen in slot 4 while the dataset stores kitchen in slot 1,
    that should still be acceptable if the shape/location/class are correct.
    """
    if not cfg.hungarian:
        return batch

    device = pred["corner_xy"].device
    bsz, max_rooms, max_corners, _ = pred["corner_xy"].shape

    out = {
        "room_valid": torch.zeros_like(batch["room_valid"]),
        "corner_valid": torch.zeros_like(batch["corner_valid"]),
        "polygon_xy": torch.zeros_like(batch["polygon_xy"]),
        "room_class": torch.zeros_like(batch["room_class"]),
        "furniture_mask": batch["furniture_mask"],
        "wall_mask": batch["wall_mask"],
        "opening_mask": batch["opening_mask"],
        "room_mask": torch.zeros_like(batch["room_mask"]),
        "boundary_mask": batch.get("boundary_mask", torch.maximum(batch["wall_mask"], batch["opening_mask"])),
        "corner_heatmap": batch.get("corner_heatmap", torch.zeros_like(batch["wall_mask"])),
    }

    with torch.no_grad():
        pred_valid_prob = torch.sigmoid(pred["room_valid_logits"]).detach()
        pred_class_logprob = F.log_softmax(pred["room_class_logits"], dim=-1).detach()
        pred_xy = pred["corner_xy"].detach()

        for bi in range(bsz):
            # finds which gt room slots are real
            gt_ids = torch.nonzero(batch["room_valid"][bi] > 0.5, as_tuple=False).flatten()
            if gt_ids.numel() == 0:
                continue

            costs = torch.zeros((max_rooms, int(gt_ids.numel())), device=device, dtype=torch.float32)
            aligned_cache: dict[tuple[int, int], torch.Tensor] = {}

            for gi_local, gi in enumerate(gt_ids.tolist()):
                n = int(batch["corner_valid"][bi, gi].sum().item())
                if n <= 0:
                    costs[:, gi_local] = 999.0
                    continue

                gt_cls = int(batch["room_class"][bi, gi].item())
                for pi in range(max_rooms):
                    aligned, coord_cost = _best_cyclic_target(
                        pred_xy[bi, pi],
                        batch["polygon_xy"][bi, gi],
                        n,
                        cfg.cyclic,
                    )
                    # If prediction pi ends up matched to ground-truth gi, the aligned version will be used as the actual target
                    aligned_cache[(pi, gi)] = aligned

                    # penalizes preds that assign low prob to correct class
                    # high prob to correct class => log prob is close to 0 => -log prob is small and vice versa
                    class_cost = -float(pred_class_logprob[bi, pi, gt_cls].item())
                    room_conf_cost = -float(torch.log(pred_valid_prob[bi, pi].clamp_min(1e-6)).item())
                    # match a prediction to a ground-truth room if it has a similar polygon, predicts the right class, and believes it is a real room
                    costs[pi, gi_local] = coord_cost + cfg.match_class_weight * class_cost + cfg.match_room_conf_weight * room_conf_cost

            cost_np = costs.detach().cpu().numpy()
            if linear_sum_assignment is not None:
                row_ind, col_ind = linear_sum_assignment(cost_np)
            else:
                row_ind, col_ind = _greedy_assignment(cost_np)

            for pi, gi_local in zip(row_ind.tolist(), col_ind.tolist()):
                gi = int(gt_ids[gi_local].item())
                out["room_valid"][bi, pi] = 1.0
                out["corner_valid"][bi, pi] = batch["corner_valid"][bi, gi]
                out["polygon_xy"][bi, pi] = aligned_cache.get((pi, gi), batch["polygon_xy"][bi, gi])
                out["room_class"][bi, pi] = batch["room_class"][bi, gi]
                out["room_mask"][bi, pi] = batch["room_mask"][bi, gi]

    return out


def polygon_loss(pred: dict[str, torch.Tensor], batch: dict[str, torch.Tensor], cfg: LossConfig | None = None):
    """
    Compute full RoomToFP loss.

    Improvement v5 additions:
    - polygon_raster_loss: softly rasterises predicted corner_xy and compares it to matched GT room_mask.
    - aux_decoder_loss: applies polygon supervision to intermediate corner-decoder outputs.
    - query-mask losses remain auxiliary; the polygon branch is now trained as the primary final output.
    """
    cfg = cfg or LossConfig()
    original_batch = batch

    # Match final prediction slots to ground-truth room objects first.
    batch = _match_and_reorder_targets(pred, original_batch, cfg)
    xy = pred["corner_xy"]
    room_valid = batch["room_valid"]

    polygon_total, polygon_parts = _polygon_supervision_terms(pred, batch, cfg)

    overlap_loss = _room_mask_overlap_loss(pred["room_mask_logits"], room_valid) if "room_mask_logits" in pred else torch.zeros((), device=xy.device, dtype=xy.dtype)

    if cfg.use_furniture and "furniture_logits" in pred and cfg.aux_furniture > 0:
        furniture_loss = _mask_loss(pred["furniture_logits"], batch["furniture_mask"], cfg)
    else:
        furniture_loss = torch.zeros((), device=xy.device, dtype=xy.dtype)

    wall_loss = _mask_loss(pred["wall_logits"], batch["wall_mask"], cfg)
    opening_loss = _mask_loss(pred["opening_logits"], batch["opening_mask"], cfg)
    boundary_loss = _mask_loss(pred["boundary_logits"], batch["boundary_mask"], cfg) if "boundary_logits" in pred else torch.zeros((), device=xy.device, dtype=xy.dtype)
    corner_heatmap_loss = _mask_loss(pred["corner_heatmap_logits"], batch["corner_heatmap"], cfg) if "corner_heatmap_logits" in pred else torch.zeros((), device=xy.device, dtype=xy.dtype)
    room_mask_loss = _room_query_mask_loss(pred["room_mask_logits"], batch["room_mask"], room_valid, cfg) if "room_mask_logits" in pred else torch.zeros((), device=xy.device, dtype=xy.dtype)

    aux_decoder_loss = torch.zeros((), device=xy.device, dtype=xy.dtype)
    aux_count = 0
    if cfg.aux_decoder_weight > 0:
        for aux_pred in pred.get("aux_outputs", []):
            aux_batch = _match_and_reorder_targets(aux_pred, original_batch, cfg)
            aux_total, _aux_parts = _polygon_supervision_terms(aux_pred, aux_batch, cfg)
            aux_decoder_loss = aux_decoder_loss + aux_total
            aux_count += 1
        if aux_count > 0:
            aux_decoder_loss = aux_decoder_loss / float(aux_count)

    total = (
        polygon_total
        + (cfg.room_overlap_weight * overlap_loss)
        + (cfg.aux_furniture * furniture_loss)
        + (cfg.aux_wall * wall_loss)
        + (cfg.aux_opening * opening_loss)
        + (cfg.aux_boundary * boundary_loss)
        + (cfg.aux_corner_heatmap * corner_heatmap_loss)
        + (cfg.aux_room_mask * room_mask_loss)
        + (cfg.aux_decoder_weight * aux_decoder_loss)
    )

    return total, {
        "room_bce": polygon_parts["room_bce"].item(),
        "corner_bce": polygon_parts["corner_bce"].item(),
        "coord_l1": polygon_parts["coord_l1"].item(),
        "edge_l1": polygon_parts["edge_l1"].item(),
        "area_l1": polygon_parts["area_l1"].item(),
        "angle": polygon_parts["angle"].item(),
        "polygon_raster_loss": polygon_parts["polygon_raster_loss"].item(),
        "aux_decoder_loss": aux_decoder_loss.item(),
        "overlap": overlap_loss.item(),
        "class": polygon_parts["class"].item(),
        "furniture_loss": furniture_loss.item(),
        "wall_loss": wall_loss.item(),
        "opening_loss": opening_loss.item(),
        "boundary_loss": boundary_loss.item(),
        "corner_heatmap_loss": corner_heatmap_loss.item(),
        "room_mask_loss": room_mask_loss.item(),
    }


def _invalid_polygon_rate(pred_xy: torch.Tensor, room_valid: torch.Tensor, corner_valid: torch.Tensor) -> torch.Tensor:
    """
    Improvement v4: quick vector-quality metric for collapsed/degenerate room polygons. Lower is better.
    """
    bad = 0
    total = 0
    with torch.no_grad():
        for bi in range(pred_xy.shape[0]):
            for ri in range(pred_xy.shape[1]):
                if room_valid[bi, ri] <= 0.5:
                    continue
                n = int(corner_valid[bi, ri].sum().item())
                if n < 3:
                    bad += 1
                    total += 1
                    continue
                pts = pred_xy[bi, ri, :n]
                area = torch.abs(_polygon_signed_area(pts)).item()
                unique = torch.unique(torch.round(pts * 1024.0).to(torch.int64), dim=0).shape[0]
                bad += int(area < 1e-4 or unique < 3)
                total += 1
    return torch.tensor(float(bad) / max(1, total), device=pred_xy.device, dtype=pred_xy.dtype)


def run_epoch(model, loader, device, opt=None, cfg: LossConfig | None = None):
    train = opt is not None
    model.train(train)
    cfg = cfg or LossConfig()

    sums = {
        "loss": 0.0,
        "coord_l1": 0.0,
        "furniture_dice": 0.0,
        "wall_dice": 0.0,
        "opening_dice": 0.0,
        "room_mask_dice": 0.0,
        "matched_room_mask_dice": 0.0,
        "invalid_polygon_rate": 0.0,
        "boundary_dice": 0.0,
        "corner_heatmap_dice": 0.0,
        "n": 0,
    }

    bar = tqdm(loader, desc="train" if train else "val")

    for batch in bar:
        batch = {k: v.to(device, non_blocking=True) for k, v in batch.items()}

        with torch.set_grad_enabled(train):
            pred = model(batch["x"])
            loss, parts = polygon_loss(pred, batch, cfg)

            if train:
                opt.zero_grad(set_to_none=True)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
                opt.step()

        bs = batch["x"].shape[0]

        sums["loss"] += loss.item() * bs
        sums["coord_l1"] += parts["coord_l1"] * bs
        if cfg.use_furniture and "furniture_logits" in pred:
            sums["furniture_dice"] += _dice_from_logits(pred["furniture_logits"], batch["furniture_mask"]).item() * bs
        sums["wall_dice"] += _dice_from_logits(pred["wall_logits"], batch["wall_mask"]).item() * bs
        sums["opening_dice"] += _dice_from_logits(pred["opening_logits"], batch["opening_mask"]).item() * bs
        if "room_mask_logits" in pred:
            valid = batch["room_valid"].unsqueeze(-1).unsqueeze(-1)
            sums["room_mask_dice"] += _dice_from_logits(pred["room_mask_logits"], batch["room_mask"] * valid).item() * bs
            # Improvement v4: compute room-mask Dice after Hungarian reordering, otherwise the metric is misleading for unordered room queries.
            matched_batch = _match_and_reorder_targets(pred, batch, cfg)
            matched_valid = matched_batch["room_valid"].unsqueeze(-1).unsqueeze(-1)
            sums["matched_room_mask_dice"] += _dice_from_logits(pred["room_mask_logits"], matched_batch["room_mask"] * matched_valid).item() * bs
            sums["invalid_polygon_rate"] += _invalid_polygon_rate(pred["corner_xy"], matched_batch["room_valid"], matched_batch["corner_valid"]).item() * bs
        if "boundary_logits" in pred:
            sums["boundary_dice"] += _dice_from_logits(pred["boundary_logits"], batch["boundary_mask"]).item() * bs
        if "corner_heatmap_logits" in pred:
            sums["corner_heatmap_dice"] += _dice_from_logits(pred["corner_heatmap_logits"], batch["corner_heatmap"]).item() * bs
        sums["n"] += bs

        postfix = {
            "loss": sums["loss"] / sums["n"],
            "coord": sums["coord_l1"] / sums["n"],
            "wdice": sums["wall_dice"] / sums["n"],
            "odice": sums["opening_dice"] / sums["n"],
            "rmdice": sums["matched_room_mask_dice"] / sums["n"],
            "badpoly": sums["invalid_polygon_rate"] / sums["n"],
            "bdice": sums["boundary_dice"] / sums["n"],
        }
        if cfg.use_furniture and "furniture_logits" in pred:
            postfix["fdice"] = sums["furniture_dice"] / sums["n"]
        bar.set_postfix(**postfix)

    return {k: v / max(1, sums["n"]) for k, v in sums.items() if k != "n"}


def _make_loaders(args, ds_all: RoomToFPDataset):
    root = Path(args.dataset_root)
    train_split = root / "train.txt"
    val_split = root / "val.txt"

    if train_split.exists() and val_split.exists():
        print("--Split-- Using train.txt and val.txt")
        train_ds = RoomToFPDataset(args.dataset_root, split="train", augment=not args.no_augment)
        val_ds = RoomToFPDataset(args.dataset_root, split="val", augment=False)
    else:
        print("--Split-- No split files found. Falling back to random split.")
        val_len = max(1, int(len(ds_all) * args.val_ratio)) if len(ds_all) > 1 else 0
        train_len = len(ds_all) - val_len
        if val_len:
            train_ds, val_ds = random_split(
                ds_all,
                [train_len, val_len],
                generator=torch.Generator().manual_seed(42),
            )
            # random_split wraps ds_all, so augmentation would apply to both. Keep it off in this fallback
            # unless the user has split files. Split files are recommended for final experiments.
        else:
            train_ds, val_ds = ds_all, None

    pin_memory = str(args.device).startswith("cuda")

    train_loader = DataLoader(
        train_ds,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.num_workers,
        pin_memory=pin_memory,
        persistent_workers=args.num_workers > 0,
    )

    val_loader = (
        DataLoader(
            val_ds,
            batch_size=args.batch_size,
            shuffle=False,
            num_workers=args.num_workers,
            pin_memory=pin_memory,
            persistent_workers=args.num_workers > 0,
        )
        if val_ds
        else None
    )

    return train_loader, val_loader, len(train_ds), len(val_ds) if val_ds else 0


def save_checkpoint(
    path: Path,
    model: torch.nn.Module,
    opt: torch.optim.Optimizer,
    scheduler,
    args,
    in_channels: int,
    epoch: int,
    best_val: float,
    best_epoch: int,
    patience_counter: int,
    history: list[dict],
    metrics: dict,
):
    ckpt = {
        "model_state_dict": model.state_dict(),
        "optimizer_state_dict": opt.state_dict(),
        "scheduler_state_dict": scheduler.state_dict() if scheduler is not None else None,
        "args": {**vars(args), "in_channels": in_channels},
        "epoch": epoch,
        "best_val": best_val,
        "best_epoch": best_epoch,
        "patience_counter": patience_counter,
        "history": history,
        "metrics": metrics,
        "val_loss": metrics.get("val", {}).get("loss", None),
    }
    torch.save(ckpt, path)


def load_checkpoint(path: Path, model: torch.nn.Module, opt: torch.optim.Optimizer, scheduler, device: str):
    checkpoint = torch.load(path, map_location=device)
    model.load_state_dict(checkpoint["model_state_dict"])

    if checkpoint.get("optimizer_state_dict") is not None:
        opt.load_state_dict(checkpoint["optimizer_state_dict"])

    if scheduler is not None and checkpoint.get("scheduler_state_dict") is not None:
        scheduler.load_state_dict(checkpoint["scheduler_state_dict"])

    start_epoch = int(checkpoint.get("epoch", 0)) + 1
    best_val = float(checkpoint.get("best_val", checkpoint.get("val_loss", float("inf"))))
    best_epoch = int(checkpoint.get("best_epoch", checkpoint.get("epoch", 0)))
    patience_counter = int(checkpoint.get("patience_counter", 0))
    history = checkpoint.get("history", [])

    return start_epoch, best_val, best_epoch, patience_counter, history


def main():
    ap = argparse.ArgumentParser(description="Train RoomToFP polygon predictor on prepared Structured3D samples.")

    ap.add_argument("--dataset-root", default="data/roomtofp_polygon")
    ap.add_argument("--output-dir", default="output/roomtofp_polygon")

    ap.add_argument("--epochs", type=int, default=50)
    ap.add_argument("--batch-size", type=int, default=2)
    ap.add_argument("--lr", type=float, default=2e-4)
    ap.add_argument("--weight-decay", type=float, default=1e-4)

    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--val-ratio", type=float, default=0.15)

    ap.add_argument("--base", type=int, default=48)  # kept for CLI compatibility
    ap.add_argument("--mask-dim", type=int, default=128, help="Improvement v3: feature width for FPN mask decoder and query-mask branch.")
    ap.add_argument("--decoder-layers", type=int, default=4, help="Improvement v3: number of Transformer decoder layers for room-query reasoning.")
    ap.add_argument("--corner-decoder-layers", type=int, default=2, help="Improvement v4: number of Transformer decoder layers for per-room corner-query reasoning.")
    ap.add_argument("--num-heads", type=int, default=8)
    ap.add_argument("--embed-dim", type=int, default=256)
    ap.add_argument("--max-rooms", type=int, default=0, help="0 means infer from dataset")
    ap.add_argument("--max-corners", type=int, default=0, help="0 means infer from dataset. Regenerate data with --max-corners 40 for best results.")
    ap.add_argument("--dropout", type=float, default=0.10)
    ap.add_argument("--num-workers", type=int, default=2)

    # augmentation, better losses, Hungarian/cyclic matching.
    ap.add_argument("--no-augment", action="store_true", help="Disable train-time flip/rotation augmentation.")
    ap.add_argument("--mask-loss", choices=["bce", "bce_dice", "focal_dice"], default="focal_dice")
    ap.add_argument("--dice-weight", type=float, default=1.0)
    ap.add_argument("--focal-gamma", type=float, default=2.0)
    ap.add_argument("--coord-weight", type=float, default=5.0)
    ap.add_argument("--polygon-edge-weight", type=float, default=0.75, help="Improvement v3: auxiliary side-length loss weight for more stable polygon shapes.")
    ap.add_argument("--polygon-angle-weight", type=float, default=0.20, help="Improvement v4: Manhattan-style edge regularisation weight.")
    ap.add_argument("--polygon-area-weight", type=float, default=0.35, help="Improvement v4: polygon area consistency weight.")
    ap.add_argument("--room-overlap-weight", type=float, default=0.10, help="Improvement v4: query-mask overlap penalty weight.")
    ap.add_argument("--polygon-raster-weight", type=float, default=1.0, help="Improvement v5: RoomFormer-style soft raster loss on predicted corner polygons.")
    ap.add_argument("--polygon-raster-size", type=int, default=64, help="Improvement v5: low-resolution raster size for polygon raster loss. 64 is fast; 96 is sharper but slower.")
    ap.add_argument("--aux-decoder-weight", type=float, default=0.35, help="Improvement v5: weight for auxiliary decoder-layer polygon losses.")
    ap.add_argument("--boundary-weight", type=float, default=0.15, help="Improvement v3: edge loss inside mask losses for sharper wall/opening boundaries.")
    ap.add_argument("--room-pos-weight-max", type=float, default=8.0, help="Improvement v3: maximum dynamic positive weight for real room slots.")
    ap.add_argument("--aux-boundary", type=float, default=0.35, help="Improvement v3: boundary heatmap auxiliary loss weight.")
    ap.add_argument("--aux-corner-heatmap", type=float, default=0.25, help="Improvement v3: corner heatmap auxiliary loss weight.")
    ap.add_argument("--aux-room-mask", type=float, default=1.0, help="Improvement v3: per-room query-mask loss weight.")
    ap.add_argument("--predict-furniture", action="store_true", help="Enable the optional furniture output head. Off by default so the model focuses on floorplan structure.")
    ap.add_argument("--use-furniture-loss", action="store_true", help="Include furniture mask loss/metrics during training. Requires --predict-furniture for a learned furniture output.")
    ap.add_argument("--aux-furniture", type=float, default=0.0, help="Furniture loss weight. Default 0.0 because furniture is trained separately later.")
    ap.add_argument("--aux-wall", type=float, default=0.8)
    ap.add_argument("--aux-opening", type=float, default=0.7)
    ap.add_argument("--no-hungarian", action="store_true", help="Disable unordered room matching and use original fixed slots.")
    ap.add_argument("--no-cyclic", action="store_true", help="Disable cyclic/reversed target polygon alignment.")
    ap.add_argument("--match-class-weight", type=float, default=0.25)
    ap.add_argument("--match-room-conf-weight", type=float, default=0.15)

    # Early stopping and checkpointing.
    ap.add_argument("--patience", type=int, default=15, help="Stop if validation loss does not improve for this many epochs.")
    ap.add_argument("--min-delta", type=float, default=1e-4, help="Minimum val loss improvement required to reset patience.")
    ap.add_argument("--save-every", type=int, default=0, help="Save checkpoint_epoch_XXXX.pt every N epochs. 0 disables periodic checkpoints.")
    ap.add_argument("--resume", default="", help="Path to checkpoint to resume from, usually last.pt or best.pt.")
    ap.add_argument("--resume-model-only", action="store_true", help="Improvement v5: load model weights from --resume but reset optimizer/scheduler/history because the loss objective changed.")
    ap.add_argument("--no-early-stop", action="store_true", help="Disable early stopping.")

    # Scheduler.
    ap.add_argument("--scheduler", choices=["none", "plateau", "cosine"], default="plateau")
    ap.add_argument("--plateau-factor", type=float, default=0.5)
    ap.add_argument("--plateau-patience", type=int, default=5)
    ap.add_argument("--min-lr", type=float, default=1e-6)

    args = ap.parse_args()

    if args.use_furniture_loss and not args.predict_furniture:
        print("[WARN] --use-furniture-loss was requested without --predict-furniture. Enabling --predict-furniture automatically.")
        args.predict_furniture = True
    if args.predict_furniture and args.aux_furniture <= 0 and args.use_furniture_loss:
        print("[WARN] --use-furniture-loss is on but --aux-furniture <= 0. Setting aux_furniture to 1.0.")
        args.aux_furniture = 1.0

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    ds = RoomToFPDataset(args.dataset_root, split=None, augment=False)
    in_channels = ds.in_channels
    dataset_max_rooms = ds.max_rooms
    dataset_max_corners = ds.max_corners
    max_rooms = dataset_max_rooms if args.max_rooms <= 0 else args.max_rooms
    max_corners = dataset_max_corners if args.max_corners <= 0 else args.max_corners

    # Improvement v3: store inferred dimensions back into args so checkpoints never save max_rooms=0/max_corners=0 again.
    args.max_rooms = int(max_rooms)
    args.max_corners = int(max_corners)
    args.in_channels = int(in_channels)

    if max_rooms != dataset_max_rooms or max_corners != dataset_max_corners:
        raise ValueError(
            f"Model target shape must match dataset shape. Dataset has max_rooms={dataset_max_rooms}, "
            f"max_corners={dataset_max_corners}; requested max_rooms={max_rooms}, max_corners={max_corners}. "
            "Regenerate the dataset with prepare_roomtofp_dataset.py if you want a different max_corners."
        )

    print(f"--Dataset-- samples={len(ds)} in_channels={in_channels} max_rooms={max_rooms} max_corners={max_corners}")

    train_loader, val_loader, train_count, val_count = _make_loaders(args, ds)
    print(f"--Dataset-- train={train_count} val={val_count}")
    print(f"--Augmentation-- train augmentation: {'off' if args.no_augment else 'on'}")
    print(f"--Matching-- Hungarian: {'off' if args.no_hungarian else 'on'} | cyclic/reversed polygon alignment: {'off' if args.no_cyclic else 'on'}")

    model = RoomToFPPolygonNet(
        in_channels=in_channels,
        max_rooms=max_rooms,
        max_corners=max_corners,
        embed_dim=args.embed_dim,
        num_heads=args.num_heads,
        decoder_layers=args.decoder_layers,
        corner_decoder_layers=args.corner_decoder_layers,
        dropout=args.dropout,
        predict_furniture=args.predict_furniture,
        base=args.base,
        mask_dim=args.mask_dim,
    ).to(args.device)

    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)

    if args.scheduler == "plateau":
        scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
            opt,
            mode="min",
            factor=args.plateau_factor,
            patience=args.plateau_patience,
            min_lr=args.min_lr,
        )
    elif args.scheduler == "cosine":
        scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=max(1, args.epochs), eta_min=args.min_lr)
    else:
        scheduler = None

    loss_cfg = _cfg_from_args(args)

    start_epoch = 1
    best = float("inf")
    best_epoch = 0
    patience_counter = 0
    history: list[dict] = []

    if args.resume:
        resume_path = Path(args.resume)
        if not resume_path.exists():
            raise FileNotFoundError(f"Resume checkpoint not found: {resume_path}")
        if args.resume_model_only:
            # Improvement v5: recommended when switching to polygon raster / auxiliary decoder losses.
            # The old best_val and optimizer state came from a different objective, so we reuse weights only.
            print(f"--Resume Model Only-- Loading model weights only: {resume_path}")
            checkpoint = torch.load(resume_path, map_location=args.device)
            model.load_state_dict(checkpoint["model_state_dict"])
            start_epoch = 1
            best = float("inf")
            best_epoch = 0
            patience_counter = 0
            history = []
        else:
            print(f"--Resume Training-- Loading checkpoint: {resume_path}")
            start_epoch, best, best_epoch, patience_counter, history = load_checkpoint(resume_path, model, opt, scheduler, args.device)
            print(f"--Resume Training-- start_epoch={start_epoch}, best_val={best:.6f}, best_epoch={best_epoch}, patience_counter={patience_counter}")

    config = {
        **vars(args),
        "in_channels": in_channels,
        "max_rooms": max_rooms,
        "max_corners": max_corners,
        "train_count": train_count,
        "val_count": val_count,
    }
    (out / "train_config.json").write_text(json.dumps(config, indent=2), encoding="utf-8")

    print("--Begin Training--")
    print(f"Output dir: {out}")
    print(f"Device: {args.device}")
    print(f"LR: {args.lr}")
    print(f"Weight decay: {args.weight_decay}")
    print(f"Mask loss: {args.mask_loss}")
    print(f"Furniture head: {'on' if args.predict_furniture else 'off'} | furniture loss: {'on' if args.use_furniture_loss else 'off'} | aux_furniture={args.aux_furniture}")
    print(f"Scheduler: {args.scheduler}")
    print(f"Early stopping: {'disabled' if args.no_early_stop else f'patience={args.patience}, min_delta={args.min_delta}'}")

    for epoch in range(start_epoch, args.epochs + 1):
        current_lr = opt.param_groups[0]["lr"]
        print(f"\nEPOCH {epoch}/{args.epochs} | lr={current_lr:.8f}")

        train_m = run_epoch(model, train_loader, args.device, opt, loss_cfg)
        val_m = run_epoch(model, val_loader, args.device, None, loss_cfg) if val_loader else train_m

        row = {"epoch": epoch, "lr": current_lr, "train": train_m, "val": val_m}
        history.append(row)

        val_loss = float(val_m["loss"])
        improved = val_loss < (best - args.min_delta)

        if scheduler is not None:
            if args.scheduler == "plateau":
                scheduler.step(val_loss)
            else:
                scheduler.step()

        if improved:
            best = val_loss
            best_epoch = epoch
            patience_counter = 0
            save_checkpoint(out / "best.pt", model, opt, scheduler, args, in_channels, epoch, best, best_epoch, patience_counter, history, row)
            print(f"--Save Best-- epoch={epoch} val_loss={best:.6f}")
        else:
            patience_counter += 1
            print(f"--No Improvements-- val_loss={val_loss:.6f} | best={best:.6f} at epoch={best_epoch} | patience={patience_counter}/{args.patience}")

        save_checkpoint(out / "last.pt", model, opt, scheduler, args, in_channels, epoch, best, best_epoch, patience_counter, history, row)

        if args.save_every > 0 and epoch % args.save_every == 0:
            save_checkpoint(out / f"checkpoint_epoch_{epoch:04d}.pt", model, opt, scheduler, args, in_channels, epoch, best, best_epoch, patience_counter, history, row)
            print(f"--Save Checkpoint-- Saved checkpoint_epoch_{epoch:04d}.pt")

        summary = {
            "current_epoch": epoch,
            "best_epoch": best_epoch,
            "best_val_loss": best,
            "patience_counter": patience_counter,
            "last_train": train_m,
            "last_val": val_m,
        }
        (out / "training_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
        (out / "history.json").write_text(json.dumps(history, indent=2), encoding="utf-8")

        if not args.no_early_stop and val_loader and patience_counter >= args.patience:
            print(f"--Early Stopping Triggered-- No validation improvement for {args.patience} epochs. Best epoch={best_epoch}, best_val_loss={best:.6f}")
            break

    print("\n--Training Complete--")
    print(f"Best epoch: {best_epoch}")
    print(f"Best validation loss: {best:.6f}")
    print(f"Best checkpoint: {out / 'best.pt'}")
    print(f"Last checkpoint: {out / 'last.pt'}")


if __name__ == "__main__":
    main()
