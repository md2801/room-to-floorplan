def seed_everything(seed: int) -> None:
    random.seed(int(seed))
    np.random.seed(int(seed))
    torch.manual_seed(int(seed))
    torch.cuda.manual_seed_all(int(seed))


def ensure_chw_mask_np(mask: np.ndarray, name: str = "mask") -> np.ndarray:
    """
    Normalise all mask arrays to C x H x W.

    This prevents dataloader batches like:
        B x 1 x 1 x H x W

    when the model expects:
        B x 1 x H x W
    """
    mask = np.asarray(mask, dtype=np.float32)

    if mask.ndim == 2:
        return mask[None, :, :].astype(np.float32)

    if mask.ndim == 3 and mask.shape[-1] == 1:
        return mask.transpose(2, 0, 1).astype(np.float32)

    if mask.ndim == 3:
        return mask.astype(np.float32)

    while mask.ndim > 3 and mask.shape[0] == 1:
        mask = np.squeeze(mask, axis=0)

    if mask.ndim == 2:
        mask = mask[None, :, :]

    if mask.ndim != 3:
        raise ValueError(f"{name} has unexpected shape after cleanup: {mask.shape}")

    return mask.astype(np.float32)


def ensure_room_masks_np(room_masks: np.ndarray, max_rooms: int, grid_size: int) -> np.ndarray:
    """
    Improvement v9: normalise room_masks to max_rooms x H x W
    """
    room_masks = np.asarray(room_masks, dtype=np.float32)

    if room_masks.ndim == 2:
        room_masks = room_masks[None, :, :]

    if room_masks.ndim == 4 and room_masks.shape[1] == 1:
        room_masks = room_masks[:, 0]

    if room_masks.ndim != 3:
        raise ValueError(f"room_masks has unexpected shape: {room_masks.shape}")

    out = np.zeros((max_rooms, grid_size, grid_size), dtype=np.float32)

    n = min(max_rooms, room_masks.shape[0])
    h = min(grid_size, room_masks.shape[1])
    w = min(grid_size, room_masks.shape[2])

    out[:n, :h, :w] = room_masks[:n, :h, :w]

    return np.clip(out, 0.0, 1.0).astype(np.float32)


def ensure_boundary_np(boundary: np.ndarray, max_rooms: int, num_points: int) -> np.ndarray:
    """
    Improvement v9: normalise dense boundary targets to max_rooms x num_points x 2
    """
    boundary = np.asarray(boundary, dtype=np.float32)

    out = np.zeros((max_rooms, num_points, 2), dtype=np.float32)

    if boundary.ndim != 3 or boundary.shape[-1] != 2:
        return out

    n_rooms = min(max_rooms, boundary.shape[0])
    n_points = min(num_points, boundary.shape[1])

    out[:n_rooms, :n_points] = boundary[:n_rooms, :n_points]

    return np.clip(out, 0.0, 1.0).astype(np.float32)


def average_dict(items: list[dict[str, float]]) -> dict[str, float]:
    if not items:
        return {}

    keys = sorted(set().union(*[x.keys() for x in items]))

    return {
        k: float(np.mean([x[k] for x in items if k in x]))
        for k in keys
    }


def move_batch(batch: dict[str, torch.Tensor], device: str) -> dict[str, torch.Tensor]:
    return {k: v.to(device, non_blocking=True) for k, v in batch.items()}


def set_optimizer_lr(optimizer: torch.optim.Optimizer, lr: float) -> None:
    for group in optimizer.param_groups:
        group["lr"] = float(lr)


def maybe_resize_tensor(
    x: torch.Tensor,
    size: int,
    mode: str = "bilinear",
) -> torch.Tensor:
    """
    Improvement v9: optionally resize dense maps before loss calculation for faster training
    """
    if size <= 0:
        return x

    if x.dim() < 4:
        return x

    h, w = x.shape[-2:]
    if h == size and w == size:
        return x

    if mode == "nearest":
        return F.interpolate(x, size=(size, size), mode="nearest")

    return F.interpolate(x, size=(size, size), mode=mode, align_corners=False)


