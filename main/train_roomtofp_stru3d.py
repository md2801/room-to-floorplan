def align_target_to_logits(target: torch.Tensor, logits: torch.Tensor) -> torch.Tensor:
    target = target.float().clamp(0.0, 1.0)

    while target.dim() > logits.dim():
        squeezed = False
        for dim in range(1, target.dim()):
            if target.shape[dim] == 1:
                target = target.squeeze(dim)
                squeezed = True
                break
        if not squeezed:
            break

    if target.dim() == logits.dim() - 1:
        target = target.unsqueeze(1)

    while target.dim() < logits.dim():
        target = target.unsqueeze(1)

    if target.shape != logits.shape:
        try:
            target = target.expand_as(logits)
        except RuntimeError as e:
            raise ValueError(
                f"Could not align target shape {tuple(target.shape)} "
                f"to logits shape {tuple(logits.shape)}"
            ) from e

    return target


def prepare_dense_pair(
    logits: torch.Tensor,
    target: torch.Tensor,
    cfg: LossConfig,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Improvement v9: optionally downsample dense logits and targets before dense losses
    """
    logits = maybe_resize_tensor(logits, cfg.dense_loss_size, mode="bilinear")

    target = target.float().clamp(0.0, 1.0)

    while target.dim() > logits.dim():
        squeezed = False
        for dim in range(1, target.dim()):
            if target.shape[dim] == 1:
                target = target.squeeze(dim)
                squeezed = True
                break
        if not squeezed:
            break

    if target.dim() == logits.dim() - 1:
        target = target.unsqueeze(1)

    while target.dim() < logits.dim():
        target = target.unsqueeze(1)

    if target.dim() >= 4 and target.shape[-2:] != logits.shape[-2:]:
        target = F.interpolate(
            target,
            size=logits.shape[-2:],
            mode="nearest",
        )

    target = align_target_to_logits(target, logits)

    return logits, target


def dice_score_from_logits(
    logits: torch.Tensor,
    target: torch.Tensor,
    threshold: float = 0.5,
    eps: float = 1e-6,
    dense_loss_size: int = 0,
) -> float:
    """
    Improvement v9: compute dice after resizing both logits and target to the same dense-loss size
    """
    if dense_loss_size > 0 and logits.dim() >= 4:
        logits = maybe_resize_tensor(logits, dense_loss_size, mode="bilinear")

    target = target.float().clamp(0.0, 1.0)

    while target.dim() > logits.dim():
        squeezed = False
        for dim in range(1, target.dim()):
            if target.shape[dim] == 1:
                target = target.squeeze(dim)
                squeezed = True
                break
        if not squeezed:
            break

    if target.dim() == logits.dim() - 1:
        target = target.unsqueeze(1)

    while target.dim() < logits.dim():
        target = target.unsqueeze(1)

    if dense_loss_size > 0 and target.dim() >= 4 and target.shape[-2:] != logits.shape[-2:]:
        target = F.interpolate(
            target,
            size=logits.shape[-2:],
            mode="nearest",
        )

    target = align_target_to_logits(target, logits)

    pred = (torch.sigmoid(logits) >= threshold).float()

    inter = (pred * target).sum()
    denom = pred.sum() + target.sum()

    if float(denom.detach().cpu()) <= 0:
        return 1.0

    return float(((2 * inter + eps) / (denom + eps)).detach().cpu())


def soft_dice_loss_from_logits(
    logits: torch.Tensor,
    target: torch.Tensor,
    eps: float = 1e-6,
) -> torch.Tensor:
    target = align_target_to_logits(target, logits)
    prob = torch.sigmoid(logits)

    dims = tuple(range(1, prob.ndim))
    inter = (prob * target).sum(dim=dims)
    denom = prob.sum(dim=dims) + target.sum(dim=dims)

    dice = (2.0 * inter + eps) / (denom + eps)
    return 1.0 - dice.mean()


def focal_bce_with_logits(
    logits: torch.Tensor,
    target: torch.Tensor,
    gamma: float = 2.0,
) -> torch.Tensor:
    target = align_target_to_logits(target, logits)

    bce = F.binary_cross_entropy_with_logits(logits, target, reduction="none")
    p = torch.sigmoid(logits)
    pt = p * target + (1.0 - p) * (1.0 - target)
    focal_weight = (1.0 - pt).pow(float(gamma))

    return (focal_weight * bce).mean()


def mask_loss(logits: torch.Tensor, target: torch.Tensor, cfg: LossConfig, resize_dense: bool = True) -> torch.Tensor:
    if resize_dense:
        logits, target = prepare_dense_pair(logits, target, cfg)
    else:
        target = align_target_to_logits(target, logits)

    if cfg.mask_loss == "bce":
        return F.binary_cross_entropy_with_logits(logits, target)

    if cfg.mask_loss == "bce_dice":
        bce = F.binary_cross_entropy_with_logits(logits, target)
        dice = soft_dice_loss_from_logits(logits, target)
        return bce + cfg.dice_weight * dice

    if cfg.mask_loss == "focal_dice":
        focal = focal_bce_with_logits(logits, target, cfg.focal_gamma)
        dice = soft_dice_loss_from_logits(logits, target)
        return focal + cfg.dice_weight * dice

    raise ValueError(f"Unknown mask loss: {cfg.mask_loss}")


def class_ce_loss(logits: torch.Tensor, target: torch.Tensor, cfg: LossConfig) -> torch.Tensor:
    weight = cfg.room_class_weights
    if weight is not None:
        weight = weight.to(device=logits.device, dtype=logits.dtype)

    return F.cross_entropy(
        logits,
        target,
        weight=weight,
        label_smoothing=float(cfg.class_label_smoothing),
    )


