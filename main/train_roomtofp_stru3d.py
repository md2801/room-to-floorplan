class RoomToFPV9NPZDataset(Dataset):
    """
    Dataset for samples/*.npz created by the v9 preprocessing pipeline.
    """

    def __init__(
        self,
        dataset_root: str | Path,
        split: str = "train",
        augment: bool = True,
        bev_noise_std: float = 0.0,
        rgb_noise_std: float = 0.0,
        structural_channel_dropout_p: float = 0.0,
        structural_pixel_dropout_p: float = 0.0,
        prior_noise_std: float = 0.0,
        max_rooms: int = 20,
        grid_size: int = 512,
    ):
        self.root = Path(dataset_root)
        self.split = str(split)
        self.augment = bool(augment and split == "train")

        # Improvement v9: augmentation is aware of 10-channel v9 input layout
        self.bev_noise_std = float(bev_noise_std)
        self.rgb_noise_std = float(rgb_noise_std)
        self.structural_channel_dropout_p = float(structural_channel_dropout_p)
        self.structural_pixel_dropout_p = float(structural_pixel_dropout_p)
        self.prior_noise_std = float(prior_noise_std)

        self.max_rooms = int(max_rooms)
        self.grid_size = int(grid_size)

        split_path = self.root / f"{split}.txt"
        if not split_path.exists():
            raise FileNotFoundError(f"Missing split file: {split_path}")

        self.names = [
            line.strip()
            for line in split_path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]

        self.sample_dir = self.root / "samples"
        if not self.sample_dir.exists():
            self.sample_dir = self.root

        if not self.names:
            raise ValueError(f"No samples listed in {split_path}")

    def __len__(self) -> int:
        return len(self.names)

    def _load(self, name: str) -> dict[str, np.ndarray]:
        path = self.sample_dir / name
        if not path.exists():
            path = self.root / name

        data = np.load(path, allow_pickle=True)
        return {k: data[k] for k in data.files}

    @staticmethod
    def _ensure_hwc_observation(sample: dict[str, np.ndarray]) -> np.ndarray:
        if "observation" in sample:
            obs = np.asarray(sample["observation"], dtype=np.float32)

            if obs.ndim != 3:
                raise ValueError(f"observation has unexpected shape: {obs.shape}")

            if obs.shape[0] in (8, 10) and obs.shape[-1] not in (8, 10):
                obs = obs.transpose(1, 2, 0)

            return obs.astype(np.float32)

        if "bev" in sample:
            bev = np.asarray(sample["bev"], dtype=np.float32)

            if bev.ndim != 3:
                raise ValueError(f"bev has unexpected shape: {bev.shape}")

            if bev.shape[0] in (8, 10):
                return bev.transpose(1, 2, 0).astype(np.float32)

            return bev.astype(np.float32)

        raise KeyError("Sample has neither observation nor bev")

    @staticmethod
    def _flip_x(sample: dict[str, np.ndarray]) -> dict[str, np.ndarray]:
        s = {k: np.array(v, copy=True) for k, v in sample.items()}

        obs = RoomToFPV9NPZDataset._ensure_hwc_observation(s)
        s["observation"] = obs[:, ::-1, :].copy()

        # Improvement v9: flip all dense v9 masks along x-axis
        for key in [
            "wall_mask",
            "opening_mask",
            "furniture_mask",
            "boundary_mask",
            "edge_mask",
            "corner_heatmap",
            "room_mask",
            "room_mask_merged",
            "distance_to_wall_target",
            "distance_to_wall",
            "input_corner_prior",
        ]:
            if key in s:
                s[key] = np.flip(s[key], axis=-1).copy()

        # Improvement v9: flip per-room masks along x-axis
        if "room_masks" in s:
            s["room_masks"] = np.flip(s["room_masks"], axis=-1).copy()

        if "polygon_xy" in s:
            s["polygon_xy"][..., 0] = 1.0 - s["polygon_xy"][..., 0]

        # Improvement v9: flip dense boundary sequence targets along x-axis
        if "boundary_64" in s:
            s["boundary_64"][..., 0] = 1.0 - s["boundary_64"][..., 0]

        # Improvement v9: flip dense boundary sequence targets along x-axis
        if "boundary_128" in s:
            s["boundary_128"][..., 0] = 1.0 - s["boundary_128"][..., 0]

        return s

    @staticmethod
    def _flip_y(sample: dict[str, np.ndarray]) -> dict[str, np.ndarray]:
        s = {k: np.array(v, copy=True) for k, v in sample.items()}

        obs = RoomToFPV9NPZDataset._ensure_hwc_observation(s)
        s["observation"] = obs[::-1, :, :].copy()

        # Improvement v9: flip all dense v9 masks along y-axis
        for key in [
            "wall_mask",
            "opening_mask",
            "furniture_mask",
            "boundary_mask",
            "edge_mask",
            "corner_heatmap",
            "room_mask",
            "room_mask_merged",
            "distance_to_wall_target",
            "distance_to_wall",
            "input_corner_prior",
        ]:
            if key in s:
                s[key] = np.flip(s[key], axis=-2).copy()

        # Improvement v9: flip per-room masks along y-axis
        if "room_masks" in s:
            s["room_masks"] = np.flip(s["room_masks"], axis=-2).copy()

        if "polygon_xy" in s:
            s["polygon_xy"][..., 1] = 1.0 - s["polygon_xy"][..., 1]

        # Improvement v9: flip dense boundary sequence targets along y-axis
        if "boundary_64" in s:
            s["boundary_64"][..., 1] = 1.0 - s["boundary_64"][..., 1]

        # Improvement v9: flip dense boundary sequence targets along y-axis
        if "boundary_128" in s:
            s["boundary_128"][..., 1] = 1.0 - s["boundary_128"][..., 1]

        return s

    def _augment_observation_v9(self, obs: np.ndarray) -> np.ndarray:
        """
        Improvement v9: apply label-safe augmentation to 10-channel BEV input

        Expected channel order:
            0 occupancy
            1 wall
            2 floor
            3 opening
            4 furniture or zero
            5 rgb_r
            6 rgb_g
            7 rgb_b
            8 observed_corner_prior
            9 distance_to_observed_wall
        """
        obs = obs.astype(np.float32, copy=True)
        h, w, c = obs.shape

        structural_channels = min(c, 5)

        if self.structural_channel_dropout_p > 0 and structural_channels > 0:
            for ch in range(structural_channels):
                if random.random() < self.structural_channel_dropout_p:
                    obs[..., ch] = 0.0

        if self.structural_pixel_dropout_p > 0 and structural_channels > 0:
            keep = (
                np.random.rand(h, w, 1).astype(np.float32)
                >= float(self.structural_pixel_dropout_p)
            )
            obs[..., :structural_channels] *= keep

        if self.bev_noise_std > 0 and structural_channels > 0:
            noise = np.random.normal(
                loc=0.0,
                scale=float(self.bev_noise_std),
                size=obs[..., :structural_channels].shape,
            ).astype(np.float32)
            obs[..., :structural_channels] = obs[..., :structural_channels] + noise

        if self.rgb_noise_std > 0 and c >= 8:
            noise = np.random.normal(
                loc=0.0,
                scale=float(self.rgb_noise_std),
                size=obs[..., 5:8].shape,
            ).astype(np.float32)
            obs[..., 5:8] = obs[..., 5:8] + noise

        # Improvement v9: keep priors stable and only add tiny noise
        if self.prior_noise_std > 0 and c >= 10:
            noise = np.random.normal(
                loc=0.0,
                scale=float(self.prior_noise_std),
                size=obs[..., 8:10].shape,
            ).astype(np.float32)
            obs[..., 8:10] = obs[..., 8:10] + noise

        obs = np.clip(obs, 0.0, 1.0)
        return obs.astype(np.float32)

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor]:
        s = self._load(self.names[idx])

        if self.augment:
            if random.random() < 0.5:
                s = self._flip_x(s)
            if random.random() < 0.5:
                s = self._flip_y(s)

        obs = self._ensure_hwc_observation(s).astype(np.float32)

        if self.augment:
            obs = self._augment_observation_v9(obs)

        h, w, c = obs.shape
        grid_size = int(h)

        wall_mask = ensure_chw_mask_np(np.clip(s["wall_mask"], 0.0, 1.0), "wall_mask")
        opening_mask = ensure_chw_mask_np(np.clip(s["opening_mask"], 0.0, 1.0), "opening_mask")
        boundary_mask = ensure_chw_mask_np(np.clip(s["boundary_mask"], 0.0, 1.0), "boundary_mask")
        corner_heatmap = ensure_chw_mask_np(np.clip(s["corner_heatmap"], 0.0, 1.0), "corner_heatmap")

        if "room_mask_merged" in s:
            room_mask_merged = ensure_chw_mask_np(np.clip(s["room_mask_merged"], 0.0, 1.0), "room_mask_merged")
        elif "room_mask" in s:
            room_mask_merged = ensure_chw_mask_np(np.clip(s["room_mask"], 0.0, 1.0), "room_mask")
        else:
            room_mask_merged = np.zeros_like(wall_mask, dtype=np.float32)

        if "room_masks" in s:
            room_masks = ensure_room_masks_np(
                np.clip(s["room_masks"], 0.0, 1.0),
                max_rooms=self.max_rooms,
                grid_size=grid_size,
            )
        else:
            # Improvement v9: fallback keeps script safe but real v9 samples should contain room_masks
            room_masks = np.zeros((self.max_rooms, grid_size, grid_size), dtype=np.float32)

        if "furniture_mask" in s:
            furniture_mask = ensure_chw_mask_np(np.clip(s["furniture_mask"], 0.0, 1.0), "furniture_mask")
        else:
            furniture_mask = np.zeros_like(wall_mask, dtype=np.float32)

        if "distance_to_wall_target" in s:
            distance_to_wall_target = ensure_chw_mask_np(
                np.clip(s["distance_to_wall_target"], 0.0, 1.0),
                "distance_to_wall_target",
            )
        else:
            # Improvement v9: fallback keeps old samples from crashing but gives zero distance supervision
            distance_to_wall_target = np.zeros_like(wall_mask, dtype=np.float32)

        polygon_xy = np.asarray(s["polygon_xy"], dtype=np.float32)
        corner_valid = np.asarray(s["corner_valid"], dtype=np.float32)
        room_valid = np.asarray(s["room_valid"], dtype=np.float32)
        room_class = np.asarray(s["room_class"], dtype=np.int64)

        boundary_64 = ensure_boundary_np(
            s["boundary_64"] if "boundary_64" in s else np.zeros((self.max_rooms, 64, 2), dtype=np.float32),
            max_rooms=self.max_rooms,
            num_points=64,
        )

        boundary_128 = ensure_boundary_np(
            s["boundary_128"] if "boundary_128" in s else np.zeros((self.max_rooms, 128, 2), dtype=np.float32),
            max_rooms=self.max_rooms,
            num_points=128,
        )

        out: dict[str, torch.Tensor] = {
            "x": torch.from_numpy(obs.transpose(2, 0, 1).astype(np.float32)).float(),
            "polygon_xy": torch.from_numpy(polygon_xy.astype(np.float32)).float(),
            "corner_valid": torch.from_numpy(corner_valid.astype(np.float32)).float(),
            "room_valid": torch.from_numpy(room_valid.astype(np.float32)).float(),
            "room_class": torch.from_numpy(room_class.astype(np.int64)).long(),

            # Improvement v9: dense polygon sequence targets
            "boundary_64": torch.from_numpy(boundary_64.astype(np.float32)).float(),
            "boundary_128": torch.from_numpy(boundary_128.astype(np.float32)).float(),

            # Dense masks
            "wall_mask": torch.from_numpy(wall_mask).float(),
            "opening_mask": torch.from_numpy(opening_mask).float(),
            "room_masks": torch.from_numpy(room_masks).float(),
            "room_mask_merged": torch.from_numpy(room_mask_merged).float(),
            "boundary_mask": torch.from_numpy(boundary_mask).float(),
            "corner_heatmap": torch.from_numpy(corner_heatmap).float(),
            "furniture_mask": torch.from_numpy(furniture_mask).float(),

            # Improvement v9: distance-to-wall target
            "distance_to_wall_target": torch.from_numpy(distance_to_wall_target).float(),
        }

        return out


