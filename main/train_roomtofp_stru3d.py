def save_checkpoint(
    path: Path,
    model: nn.Module,
    optimizer: torch.optim.Optimizer | None,
    scheduler: Any,
    epoch: int,
    best_val: float,
    best_epoch: int,
    best_visual: float,
    best_visual_epoch: int,
    args: argparse.Namespace,
    history: list[dict[str, Any]],
    ema: ModelEMA | None = None,
    model_version: str = "v9",
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    payload = {
        "epoch": int(epoch),
        "best_val": float(best_val),
        "best_epoch": int(best_epoch),
        "best_visual": float(best_visual),
        "best_visual_epoch": int(best_visual_epoch),
        "model_state_dict": model.state_dict(),
        "optimizer_state_dict": optimizer.state_dict() if optimizer is not None else None,
        "scheduler_state_dict": scheduler.state_dict() if scheduler is not None else None,
        "args": vars(args),
        "history": history,
        "model_version": model_version,
    }

    if ema is not None:
        payload["ema_state_dict"] = ema.state_dict()

    torch.save(payload, path)


def save_ema_model_checkpoint(
    path: Path,
    model: nn.Module,
    ema: ModelEMA,
    optimizer: torch.optim.Optimizer | None,
    scheduler: Any,
    epoch: int,
    best_val: float,
    best_epoch: int,
    best_visual: float,
    best_visual_epoch: int,
    args: argparse.Namespace,
    history: list[dict[str, Any]],
    model_version: str = "v9-ema",
) -> None:
    """
    Save a normal checkpoint whose model_state_dict is the EMA-smoothed weights,
    so inference works unchanged.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    raw_state = copy.deepcopy(model.state_dict())

    ema.store(model)
    ema.copy_to(model)

    payload = {
        "epoch": int(epoch),
        "best_val": float(best_val),
        "best_epoch": int(best_epoch),
        "best_visual": float(best_visual),
        "best_visual_epoch": int(best_visual_epoch),
        "model_state_dict": copy.deepcopy(model.state_dict()),
        "optimizer_state_dict": optimizer.state_dict() if optimizer is not None else None,
        "scheduler_state_dict": scheduler.state_dict() if scheduler is not None else None,
        "args": vars(args),
        "history": history,
        "model_version": model_version,
    }

    model.load_state_dict(raw_state)
    ema.restore(model)

    torch.save(payload, path)


def load_checkpoint(
    path: Path,
    model: nn.Module,
    optimizer: torch.optim.Optimizer | None = None,
    scheduler: Any = None,
    ema: ModelEMA | None = None,
    model_only: bool = False,
) -> tuple[int, float, int, float, int, list[dict[str, Any]]]:
    ckpt = torch.load(path, map_location="cpu")

    missing, unexpected = model.load_state_dict(ckpt["model_state_dict"], strict=False)

    print(f"Resume Model: Loaded {path}")

    if missing:
        print(f"Resume Model Fail - missing keys: {len(missing)}")
    if unexpected:
        print(f"Resume Model Fail - unexpected keys: {len(unexpected)}")

    if ema is not None and ckpt.get("ema_state_dict") is not None:
        ema.load_state_dict(ckpt["ema_state_dict"])
        print("Resume Model - loaded EMA state")

    if model_only:
        return 0, float("inf"), 0, -float("inf"), 0, []

    if optimizer is not None and ckpt.get("optimizer_state_dict") is not None:
        optimizer.load_state_dict(ckpt["optimizer_state_dict"])

    if scheduler is not None and ckpt.get("scheduler_state_dict") is not None:
        scheduler.load_state_dict(ckpt["scheduler_state_dict"])

    return (
        int(ckpt.get("epoch", 0)),
        float(ckpt.get("best_val", float("inf"))),
        int(ckpt.get("best_epoch", 0)),
        float(ckpt.get("best_visual", -float("inf"))),
        int(ckpt.get("best_visual_epoch", 0)),
        ckpt.get("history", []),
    )


