def mean_or_zero(xs: list[torch.Tensor], device: torch.device) -> torch.Tensor:
    return torch.stack(xs).mean() if xs else torch.zeros((), device=device)


def compute_boundary_losses_for_matches(
    pred: dict,
    batch: dict,
    matches: list[list[tuple[int, int]]],
    cfg: LossConfig,
    room_targets: torch.Tensor | None = None,
) -> tuple[torch.Tensor, dict[str, float]]:
    """
    Improvement v9: compute dense boundary losses only after sparse room-query matching
    """
    if "boundary128_xy" not in pred or "boundary64_xy" not in pred:
        device = batch["x"].device
        return torch.zeros((), device=device), {
            "boundary128_l1": 0.0,
            "boundary64_l1": 0.0,
            "boundary_point_bce": 0.0,
        }

    device = pred["boundary128_xy"].device

    boundary128_losses: list[torch.Tensor] = []
    boundary64_losses: list[torch.Tensor] = []

    for bi, pairs in enumerate(matches):
        for pi, gi in pairs:
            pred128 = pred["boundary128_xy"][bi, pi]
            tgt128 = batch["boundary_128"][bi, gi]
            aligned128 = cyclic_align_boundary_fast(pred128, tgt128, cfg.use_cyclic, stride=4)
            boundary128_losses.append(torch.abs(pred128 - aligned128).mean())

            pred64 = pred["boundary64_xy"][bi, pi]
            tgt64 = batch["boundary_64"][bi, gi]
            aligned64 = cyclic_align_boundary_fast(pred64, tgt64, cfg.use_cyclic, stride=2)
            boundary64_losses.append(torch.abs(pred64 - aligned64).mean())

    boundary128_l = mean_or_zero(boundary128_losses, device)
    boundary64_l = mean_or_zero(boundary64_losses, device)

    boundary_point_bce = torch.zeros((), device=device)

    if "boundary_point_valid_logits" in pred:
        if room_targets is None:
            room_targets = torch.zeros_like(pred["room_valid_logits"])
            for bi, pairs in enumerate(matches):
                for pi, _gi in pairs:
                    room_targets[bi, pi] = 1.0

        target = room_targets.unsqueeze(-1).expand_as(pred["boundary_point_valid_logits"])
        boundary_point_bce = F.binary_cross_entropy_with_logits(
            pred["boundary_point_valid_logits"],
            target,
        )

    total = (
        cfg.boundary128_weight * boundary128_l
        + cfg.boundary64_weight * boundary64_l
        + cfg.boundary_point_valid_weight * boundary_point_bce
    )

    parts = {
        "boundary128_l1": float(boundary128_l.detach().cpu()),
        "boundary64_l1": float(boundary64_l.detach().cpu()),
        "boundary_point_bce": float(boundary_point_bce.detach().cpu()),
    }

    return total, parts


def compute_losses(
    pred: dict,
    batch: dict,
    cfg: LossConfig,
    include_aux: bool = True,
    compute_dense: bool = True,
) -> tuple[torch.Tensor, dict[str, float]]:
    device = pred["corner_xy"].device
    matches = hungarian_match(pred, batch, cfg)

    room_targets = torch.zeros_like(pred["room_valid_logits"])

    class_losses: list[torch.Tensor] = []
    coord_losses: list[torch.Tensor] = []
    corner_bce_losses: list[torch.Tensor] = []
    edge_losses: list[torch.Tensor] = []
    area_losses: list[torch.Tensor] = []
    angle_losses: list[torch.Tensor] = []
    raster_losses: list[torch.Tensor] = []
    room_mask_losses: list[torch.Tensor] = []

    invalid_count = 0
    total_poly = 0

    for bi, pairs in enumerate(matches):
        for pi, gi in pairs:
            room_targets[bi, pi] = 1.0

            tgt_valid = batch["corner_valid"][bi, gi]
            pred_xy = pred["corner_xy"][bi, pi]
            tgt_xy = cyclic_align_target(
                pred_xy,
                batch["polygon_xy"][bi, gi],
                tgt_valid,
                cfg.use_cyclic,
            )

            valid = tgt_valid.bool()

            if valid.sum() >= 3:
                class_losses.append(
                    class_ce_loss(
                        pred["room_class_logits"][bi, pi].unsqueeze(0),
                        batch["room_class"][bi, gi].unsqueeze(0),
                        cfg,
                    )
                )

                coord_losses.append(torch.abs(pred_xy[valid] - tgt_xy[valid]).mean())

                corner_bce_losses.append(
                    F.binary_cross_entropy_with_logits(
                        pred["corner_valid_logits"][bi, pi],
                        tgt_valid,
                    )
                )

                ppoly = pred_xy[valid]
                tpoly = tgt_xy[valid]

                edge_losses.append(torch.abs(edge_lengths(ppoly) - edge_lengths(tpoly)).mean())
                area_losses.append(torch.abs(polygon_area_norm(ppoly) - polygon_area_norm(tpoly)))
                angle_losses.append(manhattan_angle_loss(ppoly))

                # Improvement v9: raster loss uses matched per-room room_masks instead of merged room_mask
                raster_losses.append(
                    polygon_raster_loss(
                        ppoly,
                        batch["room_masks"][bi, gi],
                        cfg.polygon_raster_size,
                    )
                )

                if "room_mask_logits" in pred:
                    pred_room_mask = pred["room_mask_logits"][bi, pi].unsqueeze(0).unsqueeze(0)
                    tgt_room_mask = batch["room_masks"][bi, gi].unsqueeze(0).unsqueeze(0)

                    # Improvement v9: matched query room masks are supervised with per-room instance masks at optional lower resolution
                    room_mask_losses.append(
                        mask_loss(
                            pred_room_mask,
                            tgt_room_mask,
                            cfg,
                            resize_dense=True,
                        )
                    )

                total_poly += 1

                if float(polygon_area_norm(ppoly).detach().cpu()) < 1e-4:
                    invalid_count += 1

    pos = room_targets.sum()
    neg = room_targets.numel() - pos
    pos_weight_val = float((neg / pos.clamp_min(1.0)).detach().cpu()) if pos > 0 else 1.0
    pos_weight_val = min(pos_weight_val, cfg.room_pos_weight_max)

    room_bce = F.binary_cross_entropy_with_logits(
        pred["room_valid_logits"],
        room_targets,
        pos_weight=torch.tensor(pos_weight_val, device=device),
    )

    coord_l = mean_or_zero(coord_losses, device)
    class_l = mean_or_zero(class_losses, device)
    corner_bce = mean_or_zero(corner_bce_losses, device)
    edge_l = mean_or_zero(edge_losses, device)
    area_l = mean_or_zero(area_losses, device)
    angle_l = mean_or_zero(angle_losses, device)
    raster_l = mean_or_zero(raster_losses, device)
    room_mask_l = mean_or_zero(room_mask_losses, device)

    boundary_sequence_l, boundary_parts = compute_boundary_losses_for_matches(
        pred=pred,
        batch=batch,
        matches=matches,
        cfg=cfg,
        room_targets=room_targets,
    )

    loss = (
        room_bce
        + corner_bce
        + class_l
        + cfg.coord_weight * coord_l
        + cfg.polygon_edge_weight * edge_l
        + cfg.polygon_area_weight * area_l
        + cfg.polygon_angle_weight * angle_l
        + cfg.polygon_raster_weight * raster_l
        + cfg.aux_room_mask * room_mask_l
        + boundary_sequence_l
    )

    wall_l = torch.zeros((), device=device)
    opening_l = torch.zeros((), device=device)
    boundary_l = torch.zeros((), device=device)
    corner_heat_l = torch.zeros((), device=device)
    furniture_l = torch.zeros((), device=device)
    distance_l = torch.zeros((), device=device)

    wall_dice = 0.0
    opening_dice = 0.0
    boundary_dice = 0.0
    corner_heatmap_dice = 0.0

    if compute_dense:
        if "wall_logits" in pred:
            wall_l = mask_loss(pred["wall_logits"], batch["wall_mask"], cfg, resize_dense=True)
            wall_dice = dice_score_from_logits(
                pred["wall_logits"],
                batch["wall_mask"],
                dense_loss_size=cfg.dense_loss_size,
            )

        if "opening_logits" in pred:
            opening_l = mask_loss(pred["opening_logits"], batch["opening_mask"], cfg, resize_dense=True)
            opening_dice = dice_score_from_logits(
                pred["opening_logits"],
                batch["opening_mask"],
                dense_loss_size=cfg.dense_loss_size,
            )

        if "boundary_logits" in pred:
            boundary_l = mask_loss(pred["boundary_logits"], batch["boundary_mask"], cfg, resize_dense=True)
            boundary_dice = dice_score_from_logits(
                pred["boundary_logits"],
                batch["boundary_mask"],
                dense_loss_size=cfg.dense_loss_size,
            )

        if "corner_heatmap_logits" in pred:
            corner_heat_l = mask_loss(pred["corner_heatmap_logits"], batch["corner_heatmap"], cfg, resize_dense=True)
            corner_heatmap_dice = dice_score_from_logits(
                pred["corner_heatmap_logits"],
                batch["corner_heatmap"],
                dense_loss_size=cfg.dense_loss_size,
            )

        if "furniture_logits" in pred and cfg.aux_furniture > 0:
            furniture_l = mask_loss(pred["furniture_logits"], batch["furniture_mask"], cfg, resize_dense=True)

        # Improvement v9: distance-to-wall regression teaches dense geometry awareness at optional lower resolution
        if "distance_logits" in pred and "distance_to_wall_target" in batch and cfg.distance_weight > 0:
            distance_logits = maybe_resize_tensor(
                pred["distance_logits"],
                cfg.dense_loss_size,
                mode="bilinear",
            )

            distance_target = batch["distance_to_wall_target"].float().clamp(0.0, 1.0)

            while distance_target.dim() > distance_logits.dim():
                squeezed = False
                for dim in range(1, distance_target.dim()):
                    if distance_target.shape[dim] == 1:
                        distance_target = distance_target.squeeze(dim)
                        squeezed = True
                        break
                if not squeezed:
                    break

            if distance_target.dim() == distance_logits.dim() - 1:
                distance_target = distance_target.unsqueeze(1)

            while distance_target.dim() < distance_logits.dim():
                distance_target = distance_target.unsqueeze(1)

            if distance_target.dim() >= 4 and distance_target.shape[-2:] != distance_logits.shape[-2:]:
                distance_target = F.interpolate(
                    distance_target,
                    size=distance_logits.shape[-2:],
                    mode="nearest",
                )

            distance_target = align_target_to_logits(distance_target, distance_logits)
            distance_pred = torch.sigmoid(distance_logits)
            distance_l = F.smooth_l1_loss(distance_pred, distance_target)

        loss = (
            loss
            + cfg.aux_wall * wall_l
            + cfg.aux_opening * opening_l
            + cfg.aux_boundary * boundary_l
            + cfg.aux_corner_heatmap * corner_heat_l
            + cfg.aux_furniture * furniture_l
            + cfg.distance_weight * distance_l
        )

    aux_l_total = torch.zeros((), device=device)

    if include_aux and cfg.aux_decoder_weight > 0 and pred.get("aux_outputs"):
        for aux in pred["aux_outputs"]:
            aux_loss, _ = compute_losses(
                aux,
                batch,
                cfg,
                include_aux=False,
                compute_dense=False,
            )
            aux_l_total = aux_l_total + aux_loss

        aux_l_total = aux_l_total / max(1, len(pred["aux_outputs"]))
        loss = loss + cfg.aux_decoder_weight * aux_l_total

    boundary_aux_l_total = torch.zeros((), device=device)

    # Improvement v9: optional auxiliary supervision for intermediate dense boundary decoder layers
    if include_aux and cfg.boundary_aux_decoder_weight > 0 and pred.get("boundary_aux_outputs"):
        for aux in pred["boundary_aux_outputs"]:
            aux_boundary_loss, _ = compute_boundary_losses_for_matches(
                pred=aux,
                batch=batch,
                matches=matches,
                cfg=cfg,
                room_targets=room_targets,
            )
            boundary_aux_l_total = boundary_aux_l_total + aux_boundary_loss

        boundary_aux_l_total = boundary_aux_l_total / max(1, len(pred["boundary_aux_outputs"]))
        loss = loss + cfg.boundary_aux_decoder_weight * boundary_aux_l_total

    dn_l = torch.zeros((), device=device)

    if cfg.dn_weight > 0 and "dn_outputs" in pred:
        dn = pred["dn_outputs"]
        rv = batch["room_valid"]
        cv = batch["corner_valid"]

        dn_room_bce = F.binary_cross_entropy_with_logits(dn["room_valid_logits"], rv)
        dn_corner_bce = F.binary_cross_entropy_with_logits(dn["corner_valid_logits"], cv)

        valid = (rv.unsqueeze(-1) * cv).bool()
        dn_coord = (
            torch.abs(dn["corner_xy"] - batch["polygon_xy"])[valid].mean()
            if valid.any()
            else torch.zeros((), device=device)
        )

        cls_mask = rv.bool()
        dn_cls = (
            class_ce_loss(dn["room_class_logits"][cls_mask], batch["room_class"][cls_mask], cfg)
            if cls_mask.any()
            else torch.zeros((), device=device)
        )

        dn_l = dn_room_bce + dn_corner_bce + cfg.coord_weight * dn_coord + dn_cls
        loss = loss + cfg.dn_weight * dn_l

    matched_room_mask_dice = 1.0

    if "room_mask_logits" in pred:
        vals = []
        for bi, pairs in enumerate(matches):
            for pi, gi in pairs:
                vals.append(
                    dice_score_from_logits(
                        pred["room_mask_logits"][bi, pi].unsqueeze(0).unsqueeze(0),
                        batch["room_masks"][bi, gi].unsqueeze(0).unsqueeze(0),
                        dense_loss_size=cfg.dense_loss_size,
                    )
                )
        if vals:
            matched_room_mask_dice = float(np.mean(vals))

    parts = {
        "loss": float(loss.detach().cpu()),
        "room_bce": float(room_bce.detach().cpu()),
        "coord_l1": float(coord_l.detach().cpu()),
        "class_loss": float(class_l.detach().cpu()),
        "corner_bce": float(corner_bce.detach().cpu()),
        "edge_loss": float(edge_l.detach().cpu()),
        "area_loss": float(area_l.detach().cpu()),
        "angle_loss": float(angle_l.detach().cpu()),
        "raster_loss": float(raster_l.detach().cpu()),
        "room_mask_loss": float(room_mask_l.detach().cpu()),
        "wall_loss": float(wall_l.detach().cpu()),
        "opening_loss": float(opening_l.detach().cpu()),
        "boundary_mask_loss": float(boundary_l.detach().cpu()),
        "corner_heatmap_loss": float(corner_heat_l.detach().cpu()),
        "distance_loss": float(distance_l.detach().cpu()),
        "wall_dice": float(wall_dice),
        "opening_dice": float(opening_dice),
        "boundary_dice": float(boundary_dice),
        "corner_heatmap_dice": float(corner_heatmap_dice),
        "matched_room_mask_dice": float(matched_room_mask_dice),
        "invalid_polygon_rate": float(invalid_count / max(1, total_poly)),
        "aux_decoder_loss": float(aux_l_total.detach().cpu()),
        "boundary_aux_decoder_loss": float(boundary_aux_l_total.detach().cpu()),
        "dn_loss": float(dn_l.detach().cpu()),
        **boundary_parts,
    }

    return loss, parts


